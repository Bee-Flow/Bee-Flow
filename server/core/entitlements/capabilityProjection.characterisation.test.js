'use strict';
/**
 * Characterisation of the capability projection as the entitlement routes serialise it
 * (GET /auth/my-entitlements for an organisation admin and for a plain member, and the
 * Access & Permissions matrix GET /auth/organizations/:orgId/group-access), in a cloud and in a
 * self-hosted installation. Recorded by capabilityProjection.testkit.js in a child process.
 *
 * 1. With every module present the projection equals the golden, byte for byte: what a client
 *    is offered does not change while the modules move out of the core.
 * 2. With every module hidden (BEEFLOW_HIDE_MODULES=all) the projection is the same minus exactly
 *    the capabilities of the first-party modules (modules/firstParty/capabilityOwners.json, and the
 *    catalog's capabilityIds for a catalog module): an absent module offers nothing, and nothing
 *    else moves.
 *
 * Regenerate (only after a change that is MEANT to change the projection; review the diff):
 *   cd server && UPDATE_GOLDEN=1 node --test core/entitlements/capabilityProjection.characterisation.test.js
 */

const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const { render } = require('../../boot/compositionGolden.testkit');

const SERVER = path.resolve(__dirname, '..', '..');
const GOLDEN = path.join(__dirname, 'capabilityProjection.characterisation.golden.json');
const COMMENT = 'Generated by core/entitlements/capabilityProjection.characterisation.test.js (UPDATE_GOLDEN=1) from a child process '
    + '(core/entitlements/capabilityProjection.testkit.js) with every module present: GET /auth/my-entitlements for an organisation '
    + 'admin and a member, and GET /auth/organizations/o1/group-access, in a cloud and a self-hosted installation.';
/** Switches that decide which modules are present; the child gets only the ones a test sets. */
const SWITCHES = ['BEEFLOW_HIDE_MODULES', 'BEEFLOW_EDITION', 'BEEFLOW_MODULES', 'DEPLOYMENT_MODE', 'NODE_TEST_CONTEXT'];

/**
 * The projection, recorded in a child process with `extra` on top of a clean environment.
 * @param {Record<string, string>} extra
 * @returns {Record<string, any>}
 */
function record(extra) {
    const out = path.join(os.tmpdir(), `bf-capability-projection-${process.pid}-${Date.now()}.json`);
    const env = { ...process.env };
    for (const name of SWITCHES) delete env[name];
    Object.assign(env, extra);
    try {
        const res = spawnSync(process.execPath, [
            '--require', path.join(SERVER, 'moduleRoots.cjs'), '--require', path.join(SERVER, 'testUtils', 'registerFeatures.js'),
            path.join(__dirname, 'capabilityProjection.testkit.js'), out,
        ], { cwd: SERVER, env, encoding: 'utf8', timeout: 120_000, maxBuffer: 64 * 1024 * 1024 });
        assert.equal(res.status, 0, String(res.stderr || res.error).split('\n').slice(-25).join('\n'));
        return JSON.parse(fs.readFileSync(out, 'utf8'));
    } finally {
        fs.rmSync(out, { force: true });
    }
}

/** Every capability id a first-party module offers: the record for the others, the catalog for a catalog module. */
function firstPartyCapabilityIds() {
    const owners = require('../../modules/firstParty/capabilityOwners.json');
    const { getModule } = require('../../modules/catalog');
    const ids = new Set(Object.keys(owners.capabilities));
    for (const id of owners.catalogModules) for (const cap of getModule(id)?.capabilityIds || []) ids.add(cap);
    return ids;
}

/**
 * `value` with every trace of the ids in `gone` removed: list entries that are such an id or an
 * object with such an `id`, and object keys that are such an id.
 * @param {unknown} value
 * @param {Set<string>} gone
 * @returns {unknown}
 */
function without(value, gone) {
    if (Array.isArray(value)) {
        return value
            .filter((v) => !(typeof v === 'string' && gone.has(v)) && !(v && typeof v === 'object' && gone.has(v.id)))
            .map((v) => without(v, gone));
    }
    if (value && typeof value === 'object') {
        return Object.fromEntries(Object.entries(value).filter(([k]) => !gone.has(k)).map(([k, v]) => [k, without(v, gone)]));
    }
    return value;
}

test('with every module present the projection is the recorded one', () => {
    const recording = record({});
    if (process.env.UPDATE_GOLDEN === '1') fs.writeFileSync(GOLDEN, `${render({ _comment: COMMENT, ...recording })}\n`);
    const golden = JSON.parse(fs.readFileSync(GOLDEN, 'utf8'));
    delete golden._comment;
    assert.deepEqual(recording, golden);
});

test('with every module hidden, exactly the capabilities of the first-party modules are left out', () => {
    const full = record({});
    const core = record({ BEEFLOW_HIDE_MODULES: 'all' });
    const owned = firstPartyCapabilityIds();
    const fullIds = new Set(full.cloud.member.registry.map((/** @type {{ id: string }} */ c) => c.id));
    const dropped = [...owned].filter((id) => fullIds.has(id));
    assert.ok(dropped.length > 20, `only ${dropped.length} first-party capabilities are in the full registry`);
    for (const id of dropped) assert.ok(!core.cloud.member.registry.some((/** @type {{ id: string }} */ c) => c.id === id), `${id} is still offered`);
    assert.deepEqual(core, without(full, owned));
});
