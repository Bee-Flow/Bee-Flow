// @typecheck
/**
 * The observed route contract: the walked router classified against the static
 * sweep, the registry and the open-route list. Shared by routes.contract.test.js
 * and scripts/gen-routes-contract.mjs so both read the router the same way.
 *
 * `walked` is the route table scripts/api-reference-walk.cjs reports (through
 * gen-api-reference.mjs walkServer); the caller runs that walk, because it is a
 * child process that loads the whole app.
 */

'use strict';

const fs = require('node:fs');
const path = require('node:path');

const rc = require('../auth/routeContract');
const registry = require('../auth/accessRegistry');
const { OPEN_ROUTES, OPEN_ROUTES_WALK_ONLY } = require('../auth/openRoutes');
const { parseSurface } = require('./routeSurfaceSweep');

const SERVER = path.resolve(__dirname, '..');
// Next to the registry it extends: auth/accessRegistry.js is the hand-written
// overlay, this file the generated class per route.
const CONTRACT_REL = 'auth/routes.contract.json';

/** @param {string} server */
function readSourceFrom(server) {
    return (/** @type {string} */ rel) => {
        try {
            const p = path.join(server, rel);
            return fs.statSync(p).isFile() ? fs.readFileSync(p, 'utf8') : null;
        } catch (_) { return null; }
    };
}

/**
 * @param {import('../auth/routeContract').WalkedRoute[] | { routes: import('../auth/routeContract').WalkedRoute[] }} walk  the walk, or its route table
 * @param {{ server?: string }} [opts]
 */
function observeContract(walk, { server = SERVER } = {}) {
    const walked = Array.isArray(walk) ? walk : walk.routes;
    // The sweep test skips the triaged prefixes (the drift test covers those in
    // depth); the contract wants the handler evidence for every route, so no prefix
    // is skipped here.
    const surface = parseSurface(readSourceFrom(server), 'index.js', {});
    const open = new Map([...OPEN_ROUTES, ...OPEN_ROUTES_WALK_ONLY]);
    return rc.buildContract(walked, { surface, registry, open });
}

/** @param {string} [server] */
function contractPath(server = SERVER) {
    return path.join(server, CONTRACT_REL);
}

/** @param {string} [server] */
function readContract(server = SERVER) {
    const p = contractPath(server);
    if (!fs.existsSync(p)) return null;
    return JSON.parse(fs.readFileSync(p, 'utf8'));
}

/**
 * The file's text: a header that says where it comes from, then the routes.
 * @param {Record<string, import('../auth/routeContract').ContractEntry>} routes
 */
function renderContract(routes) {
    const doc = {
        _comment: 'Generated by scripts/gen-routes-contract.mjs from the server router: the gate class every route is held to (auth/routeContract.js). routes.contract.test.js fails when a route is missing here or carries a weaker gate than recorded. After a route change: npm run gen:routes-contract, then review the diff: a class that went DOWN is the change to look at.',
        version: 1,
        routes,
    };
    return `${JSON.stringify(doc, null, 2)}\n`;
}

module.exports = { observeContract, contractPath, readContract, renderContract, CONTRACT_REL };
