'use strict';
/**
 * Characterisation of the STORES whose schema boot and `npm run db:migrate`
 * initialise, in order, as the two functions that run them see them:
 *
 *   boot     boot/storeSchemas.js startStoreSchemas(): what the SERVER starts
 *            after listen (it iterates STORE_MODULES of storeModules.js);
 *   migrate  storeModules.js collectStoreModules(): what migrateDb.js awaits
 *            (STORE_MODULES, then the storeModules of every available catalog
 *            module, deduplicated by name).
 *
 * Today the two lists are equal (no catalog module declares storeModules); the
 * golden records both, so a move that makes them differ is seen. The ORDER is
 * part of the contract (user schema first, datatableStore after
 * automationStore, see storeModules.js), so both are compared exactly.
 *
 * Regenerate: cd server && UPDATE_GOLDEN=1 node --test boot/composition.stores.characterisation.test.js
 */
const { test } = require('node:test');
const assert = require('node:assert/strict');

const { readGolden } = require('./compositionGolden.testkit');
const { startStoreSchemas } = require('./storeSchemas');
const { collectStoreModules } = require('../storeModules');

const COMMENT = 'Generated by boot/composition.stores.characterisation.test.js (UPDATE_GOLDEN=1). `boot`: the stores '
    + 'boot/storeSchemas.js startStoreSchemas() starts, in order, recorded through its `load` seam (the list the server uses). '
    + '`migrate`: storeModules.js collectStoreModules(), the list migrateDb.js awaits. Compared exactly, order included.';

const quiet = { info() {}, warn() {}, error() {}, log() {} };

function record() {
    /** @type {string[]} */
    const loaded = [];
    const report = startStoreSchemas({
        log: quiet,
        load: (file) => { loaded.push(file); return { initDB: () => Promise.resolve() }; },
    });
    assert.deepEqual(report.unverified, []);
    assert.deepEqual(report.failed, []);
    const boot = report.started.map((name, i) => ({ name, file: loaded[i] }));
    const migrate = collectStoreModules(/** @type {Console} */ (/** @type {unknown} */ (quiet))).map(({ name, file }) => ({ name, file }));
    return { boot, migrate };
}

test('boot and db:migrate initialise the same stores, in the same order, as recorded', () => {
    const recording = record();
    const golden = readGolden('stores', COMMENT, recording);
    assert.deepEqual(recording.boot, golden.boot, 'boot/storeSchemas.js starts other stores, or in another order');
    assert.deepEqual(recording.migrate, golden.migrate, 'collectStoreModules() (db:migrate) lists other stores, or in another order');
    assert.ok(recording.boot.length >= 70, `suspiciously few stores: ${recording.boot.length}`);
});
