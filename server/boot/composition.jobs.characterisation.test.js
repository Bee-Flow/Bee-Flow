'use strict';
/**
 * Characterisation of the background JOBS boot starts, per startup phase, and
 * of the shutdown sequence, recorded by boot/compositionJobs.testkit.cjs in a
 * child process: runStartupChecks() and every function of STARTUP_PHASES
 * (boot/startupTasks.js) run with every module they require replaced by a
 * recorder (Module._load intercepted; nothing real starts), their deferred
 * timer callbacks run once inside the same phase, then the SIGTERM handler of
 * boot/lifecycle.js installGracefulShutdown() runs the same way.
 *
 * Every phase is recorded the same way: by its calls ({ module tree path,
 * method }) and by the set of modules it requires. No phase needed the
 * fallback of "requires only"; `requires` is recorded next to the calls so a
 * require kept for its side effect (compliance/checks) is covered too.
 *
 * Assertions: the phase list in order; per phase the SET of calls and the SET
 * of required modules (order inside a phase may change when module jobs are
 * replayed after the core's); the shutdown calls in their exact ORDER (the
 * drain comes before the pushers stop, Redis before the blob engines, OTEL
 * last).
 *
 * Regenerate: cd server && UPDATE_GOLDEN=1 node --test boot/composition.jobs.characterisation.test.js
 */
const { test } = require('node:test');
const assert = require('node:assert/strict');

const { readGolden, multisetDiff, describeMultisetDiff } = require('./compositionGolden.testkit');
const { runRecorder } = require('./compositionChild.testkit');

const COMMENT = 'Generated by boot/composition.jobs.characterisation.test.js (UPDATE_GOLDEN=1) from a child process '
    + '(boot/compositionJobs.testkit.cjs): per startup phase (runStartupChecks, then STARTUP_PHASES of boot/startupTasks.js) '
    + 'the calls made on the modules it requires ({ module tree path, method }, every module a recorder, deferred timers run once '
    + 'in the phase) and the modules it requires; `shutdown` the calls of the SIGTERM handler of boot/lifecycle.js in order. '
    + 'Default environment: BEEFLOW_EDITION, DEPLOYMENT_MODE and the per-job switches unset. Phases compared as sets, shutdown in order.';

/** @type {any} */
let recording;
/** @type {any} */
let golden;

test('record the startup phases and the shutdown', () => {
    recording = runRecorder('compositionJobs.testkit.cjs');
    golden = readGolden('jobs', COMMENT, recording);
    assert.ok(recording.phases.length >= 10, 'suspiciously few phases');
});

test('the same phases, in the same order', () => {
    assert.deepEqual(recording.phases.map((/** @type {any} */ p) => p.phase), golden.phases.map((/** @type {any} */ p) => p.phase));
});

test('every phase starts the same jobs and requires the same modules', () => {
    const problems = [];
    for (const want of golden.phases) {
        const got = recording.phases.find((/** @type {any} */ p) => p.phase === want.phase) || { calls: [], requires: [] };
        const calls = multisetDiff(want.calls, got.calls);
        const requires = multisetDiff(want.requires, got.requires);
        if (calls.missing.length || calls.added.length) problems.push(`${want.phase} calls:\n${describeMultisetDiff(calls)}`);
        if (requires.missing.length || requires.added.length) problems.push(`${want.phase} requires:\n${describeMultisetDiff(requires)}`);
    }
    assert.deepEqual(problems, []);
});

test('the shutdown makes the same calls in the same order', () => {
    assert.deepEqual(recording.shutdown, golden.shutdown);
    assert.deepEqual(recording.shutdown.at(-1), { module: 'process', method: 'exit(0)' });
});
