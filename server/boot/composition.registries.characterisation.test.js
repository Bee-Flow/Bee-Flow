'use strict';
/**
 * Characterisation of what core's REGISTRIES hold once boot/featureRegistrations.js
 * has loaded the way index.js loads it, recorded by
 * boot/compositionRegistries.testkit.cjs in a child process:
 *
 *   featureModules      core/featureModules.js featureModuleNames()
 *   toolFamilies        core/tools/toolFamilyRegistry.js listToolFamilies(): name and order, in walk order
 *   toolsets            integrations/coreToolsets.js TOOLSETS: key and number of tools, in key order
 *   runnerPorts         core/automationRunner/featurePorts.js runnerPortNames(), with each port's functions
 *   integrationClients  core/integrations/integrationClients.js integrationClientNames()
 *   erasurePorts        stores/user/erasurePorts.js erasurePortNames()
 *   datatableListeners  stores/datatableStore/liveChanges.js liveListenerLabels()
 *   setters             every set<Name>() export called while the registrations loaded
 *                       (the late-bound ports of boot/lateBoundPorts.js), as { module, setter }
 *
 * The tool-family walk order decides which family answers a tool name, and the
 * toolset key order is the order tools are offered in: both are compared
 * exactly. The other registries are maps by name, so they are compared as sets
 * (a loader that replays module registrations after the core's may change the
 * order in which names arrive, not what they resolve to).
 *
 * Regenerate: cd server && UPDATE_GOLDEN=1 node --test boot/composition.registries.characterisation.test.js
 */
const { test } = require('node:test');
const assert = require('node:assert/strict');

const { readGolden } = require('./compositionGolden.testkit');
const { runRecorder } = require('./compositionChild.testkit');

const COMMENT = 'Generated by boot/composition.registries.characterisation.test.js (UPDATE_GOLDEN=1) from a child process '
    + '(boot/compositionRegistries.testkit.cjs) that requires boot/featureRegistrations.js as index.js does, with every module '
    + 'available. toolFamilies and toolsets are compared in order; the other lists as sets. `setters` are the set<Name>() '
    + 'exports called while the registrations loaded; `unwrappable` the modules whose exports could not be wrapped (ES modules).';

const EXACT = ['toolFamilies', 'toolsets'];
const AS_SET = ['featureModules', 'runnerPorts', 'integrationClients', 'erasurePorts', 'datatableListeners', 'setters', 'unwrappable'];

/** @type {Record<string, any[]>} */
let recording;
/** @type {Record<string, any[]>} */
let golden;

const sorted = (/** @type {any[]} */ list) => list.map((x) => JSON.stringify(x)).sort();

test('record the registries after boot/featureRegistrations.js', () => {
    recording = runRecorder('compositionRegistries.testkit.cjs');
    golden = readGolden('registries', COMMENT, recording);
    assert.deepEqual(Object.keys(recording).sort(), [...EXACT, ...AS_SET].sort());
});

for (const key of EXACT) {
    test(`${key}: the same entries in the same order`, () => {
        assert.deepEqual(recording[key], golden[key]);
    });
}

for (const key of AS_SET) {
    test(`${key}: the same entries`, () => {
        assert.deepEqual(sorted(recording[key]), sorted(golden[key]));
    });
}

test('the late-bound ports are filled: every setter of boot/lateBoundPorts.js was called', () => {
    const setters = recording.setters.map((s) => s.setter);
    for (const name of ['setAutomationExecutor', 'setOrgShieldResolver', 'setLegacySecretResolver', 'setApplyPlanToOrg',
        'setMaybeAutoGrantOrgTrial', 'setSeatSync', 'setSourceSync', 'setConversationStateCleaner', 'setAutoSyncResource']) {
        assert.ok(setters.includes(name), `${name} was not called`);
    }
});
