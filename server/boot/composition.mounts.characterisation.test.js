'use strict';
/**
 * Characterisation of what server/index.js MOUNTS: the ordered list of every
 * app.use() call, app-level route and stray layer on the Express app, and the
 * use() calls of the /ai router (routes/ai.js), recorded from the real app by
 * boot/compositionMounts.testkit.cjs (database stubbed, no port bound).
 *
 * The plan moves module mounts out of index.js into per-module composition
 * files that a loader replays into slots. That regroups mounts and changes
 * absolute positions ON PURPOSE, so this test asserts two things that survive
 * a correct move and fail a wrong one:
 *   (a) the multiset of mounts (path, chain, router fingerprint) is the golden's;
 *   (b) every pair of mounts whose paths OVERLAP (equal; one a prefix of the
 *       other on a segment boundary, a `:param` segment matching any segment;
 *       or either at '/' or without a path) keeps its relative order.
 * The JSON 404 layer, the marketing renderer, the SPA fallback and the terminal
 * error handler are ordinary path-less entries, so (b) pins them behind every
 * router.
 *
 * Route level: auth/routes.contract.json (every route with its gate class,
 * routes.contract.test.js) is the proof per route; this file does not repeat it.
 *
 * Regenerate: cd server && UPDATE_GOLDEN=1 node --test boot/composition.mounts.characterisation.test.js
 */
const { test } = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');

const { readGolden, multisetDiff, describeMultisetDiff } = require('./compositionGolden.testkit');
const { runRecorder } = require('./compositionChild.testkit');

const SERVER = path.resolve(__dirname, '..');

const COMMENT = [
    'Generated by boot/composition.mounts.characterisation.test.js (UPDATE_GOLDEN=1) from the real server/index.js,',
    'loaded by boot/compositionMounts.testkit.cjs through auth/routeWalk.cli.js. `app` is the stack of the Express app,',
    'one entry per app.use() call, app-level route or stray layer; `ai` the use() calls of the /ai router.',
    'Recorded with NODE_ENV=production (agent-hub/dist faked present, so the static mounts and the SPA fallback are in it)',
    'and every mount switch in its default state: STUDIO_MCP_ENABLED, AUTOMATION_MCP_ENABLED, CMS_MCP_ENABLED,',
    'SEARCH_ROUTER_ENABLED and WEBPAGE_FULL_RUNTIME_ENABLED unset. `mcpOn` is the app stack with the three MCP switches',
    'set to 1. Mounts made after listen() (the webpage full-tier proxy) are not recorded. Per chain function: kind',
    '(router | gate | fn), name, the route-contract class (auth/routeContract.js chainClass), the gate tag; a router',
    'carries the count and a sha256 prefix of its sorted "METHOD path" table. `pos` is the position; the test compares',
    'the multiset and the relative order of overlapping paths, not positions. Routes: auth/routes.contract.json.',
].join(' ');

/**
 * The walk, in the fixed environment of the API reference walk (dummy secrets, no repo .env).
 * @param {'default' | 'mcp'} switches
 */
async function walk(switches) {
    const { walkEnv } = await import(path.join(SERVER, '..', 'scripts', 'gen-api-reference.mjs'));
    return runRecorder('compositionMounts.testkit.cjs', [switches], { env: walkEnv(), timeoutMs: 180_000 });
}

/** @param {Array<Record<string, unknown>>} entries */
const numbered = (entries) => entries.map((e, pos) => ({ pos, ...e }));

/** The identity of a mount: everything but its position. @param {Record<string, unknown>} e */
const keyOf = ({ pos: _pos, ...rest }) => JSON.stringify(rest);

/** @param {unknown} p */
const segmentsOf = (p) => (p === null || p === undefined || p === '/' ? [] : String(p).split('/').filter(Boolean));

/** Do two mount paths overlap? @param {unknown} a @param {unknown} b */
function overlaps(a, b) {
    const sa = segmentsOf(a);
    const sb = segmentsOf(b);
    if (!sa.length || !sb.length) return true;
    const n = Math.min(sa.length, sb.length);
    for (let i = 0; i < n; i += 1) {
        if (sa[i] !== sb[i] && !sa[i].startsWith(':') && !sb[i].startsWith(':')) return false;
    }
    return true;
}

/**
 * Each entry keyed by its identity plus its occurrence (the 2nd identical mount is `#1`).
 * @param {Array<Record<string, unknown>>} entries
 */
function occurrenceKeys(entries) {
    /** @type {Map<string, number>} */
    const seen = new Map();
    return entries.map((e) => {
        const k = keyOf(e);
        const n = seen.get(k) || 0;
        seen.set(k, n + 1);
        return `${k}#${n}`;
    });
}

/**
 * The overlapping pairs of the golden whose order the recording does not keep.
 * @param {Array<Record<string, unknown>>} golden
 * @param {Array<Record<string, unknown>>} actual
 */
function orderViolations(golden, actual) {
    const gKeys = occurrenceKeys(golden);
    const aPos = new Map(occurrenceKeys(actual).map((k, i) => [k, i]));
    const broken = [];
    let pairs = 0;
    for (let i = 0; i < golden.length; i += 1) {
        for (let j = i + 1; j < golden.length; j += 1) {
            if (!overlaps(golden[i].path, golden[j].path)) continue;
            pairs += 1;
            const pi = aPos.get(gKeys[i]);
            const pj = aPos.get(gKeys[j]);
            if (pi === undefined || pj === undefined) continue; // the multiset check reports it
            if (pi > pj) broken.push(`  ${golden[i].path} (golden #${i}) must stay before ${golden[j].path} (golden #${j})`);
        }
    }
    return { pairs, broken };
}

/** @param {string} label @param {Array<Record<string, unknown>>} golden @param {Array<Record<string, unknown>>} actual */
function assertSameComposition(label, golden, actual) {
    const diff = multisetDiff(golden, actual, keyOf);
    assert.ok(!diff.missing.length && !diff.added.length, `${label}: the mounts differ from the golden:\n${describeMultisetDiff(diff)}`);
    const { pairs, broken } = orderViolations(golden, actual);
    assert.ok(pairs > 0, `${label}: no overlapping pairs to check`);
    assert.deepEqual(broken, [], `${label}: overlapping mounts changed order:\n${broken.join('\n')}`);
    return pairs;
}

/** @type {Record<string, any>} */
let recording;
/** @type {Record<string, any>} */
let golden;

test('record the mounts of the real app (default switches, then the MCP switches on)', async () => {
    const [plain, mcp] = await Promise.all([walk('default'), walk('mcp')]);
    recording = { app: numbered(plain.app), ai: numbered(plain.ai), mcpOn: numbered(mcp.app) };
    golden = readGolden('mounts', COMMENT, recording);
    assert.ok(recording.app.length > 100, `suspiciously few mounts: ${recording.app.length}`);
});

test('app: the same mounts, and overlapping mounts in the same order', () => {
    assertSameComposition('app', golden.app, recording.app);
});

test('/ai router: the same sub-routers, and overlapping ones in the same order', () => {
    assertSameComposition('ai', golden.ai, recording.ai);
});

test('MCP switches on: the same mounts, and overlapping mounts in the same order', () => {
    assertSameComposition('mcpOn', golden.mcpOn, recording.mcpOn);
    const extra = multisetDiff(recording.app, recording.mcpOn, keyOf).added.map((k) => JSON.parse(k).path).sort();
    assert.deepEqual(extra, ['/mcp/automations', '/mcp/cms', '/mcp/studio']);
});

test('the fallbacks stay behind every router: JSON 404, marketing render, SPA fallback, terminal error handler', () => {
    const tail = recording.app.slice(-4).map((/** @type {any} */ e) => [e.path, e.chain.map((/** @type {any} */ c) => c.name).join(',')]);
    assert.deepEqual(tail.map((t) => t[0]), [null, null, null, null]);
    assert.equal(tail[3][1], 'terminalErrorHandler');
});

test('overlap: equal, prefix on a segment boundary, a :param segment, a root or path-less mount', () => {
    assert.ok(overlaps('/auth', '/auth'));
    assert.ok(overlaps('/auth', '/auth/mfa'));
    assert.ok(!overlaps('/api/usage', '/api/usage-x'));
    assert.ok(overlaps('/api/organizations/:orgId/x', '/api/organizations/o1'));
    assert.ok(overlaps(null, '/w') && overlaps('/', '/w'));
    assert.ok(!overlaps('/share', '/w'));
    const a = { path: '/a', chain: [] };
    const b = { path: '/a/b', chain: [] };
    const c = { path: '/c', chain: [] };
    assert.deepEqual(orderViolations([a, c, b], [c, a, b]).broken, [], 'a disjoint mount may move');
    assert.equal(orderViolations([a, c, b], [b, c, a]).broken.length, 1, 'overlapping mounts may not swap');
});
