'use strict';
/**
 * Characterisation of the boot migration ladder of boot/bootMigrations.js as
 * the functions that run it see it: runLooseMigrations() and
 * runNlTranslations() are called through their `load` / `ledger` seam with an
 * empty ledger and every migration a recorder, so the golden holds the names
 * in the order each runner actually ran them.
 * MANUAL_MIGRATIONS is a list only (migrateDb.js names it and never runs it).
 *
 * Order is compared exactly: the NL catalogues read-modify-write one row and a
 * later catalogue's Dutch wins (see the comments in bootMigrations.js).
 * The registration test of these lists, boot/bootMigrations.test.js, reads the
 * exported lists (not the text of bootMigrations.js) and needs no change.
 *
 * Regenerate: cd server && UPDATE_GOLDEN=1 node --test boot/composition.migrations.characterisation.test.js
 */
const { test } = require('node:test');
const assert = require('node:assert/strict');

const { readGolden } = require('./compositionGolden.testkit');
const { runLooseMigrations, runNlTranslations, MANUAL_MIGRATIONS } = require('./bootMigrations');

const COMMENT = 'Generated by boot/composition.migrations.characterisation.test.js (UPDATE_GOLDEN=1): the names '
    + 'runLooseMigrations() and runNlTranslations() of boot/bootMigrations.js ran, in order, against an empty ledger '
    + '(through their load / ledger seam: nothing real runs), and the MANUAL_MIGRATIONS list. Compared exactly.';

const quiet = { info() {}, warn() {}, error() {}, log() {} };

/**
 * The names a runner asks for, in order, with an empty ledger and every migration a recorder.
 * @param {typeof runLooseMigrations} run
 */
async function namesRun(run) {
    /** @type {string[]} */
    const ran = [];
    const out = await run({
        log: quiet,
        load: (name) => ({ up: async () => { ran.push(name); } }),
        ledger: { read: async () => new Map(), record: async () => {} },
    });
    assert.deepEqual(out.failed, []);
    assert.deepEqual(out.ok, ran, 'every migration the runner loaded is reported as run');
    return ran;
}

test('the boot ladder runs the same migrations and catalogues, in the same order, as recorded', async () => {
    const recording = {
        looseMigrations: await namesRun(runLooseMigrations),
        nlTranslations: await namesRun(runNlTranslations),
        manualMigrations: [...MANUAL_MIGRATIONS],
    };
    const golden = readGolden('migrations', COMMENT, recording);
    assert.deepEqual(recording.looseMigrations, golden.looseMigrations, 'runLooseMigrations() runs other migrations, or in another order');
    assert.deepEqual(recording.nlTranslations, golden.nlTranslations, 'runNlTranslations() runs other catalogues, or in another order');
    assert.deepEqual(recording.manualMigrations, golden.manualMigrations, 'MANUAL_MIGRATIONS changed');
    const { looseMigrations: loose, nlTranslations: nl } = recording;
    assert.ok(loose.length > 20 && nl.length > 50, `suspiciously short ladder: ${loose.length} + ${nl.length}`);
});
