# ── Answers ─────────────────────────────────────────────────────────────
# A check takes one value. It answers 0 with the value to use in CLEAN, or 1
# with what is wrong in PROBLEM. Plain character checks only.
CLEAN=''
PROBLEM=''

trim() { # value → the value without surrounding blanks, on stdout
    local v="$1"
    v="${v#"${v%%[![:space:]]*}"}"
    v="${v%"${v##*[![:space:]]}"}"
    printf '%s' "$v"
}

check_host() {
    local host="${1,,}" label
    PROBLEM='Enter the name or IPv4 address of this machine, for example 192.168.1.20 or beeflow.example.com (no http://, no port).'
    [ -n "$host" ] && [ "${#host}" -le 253 ] || return 1
    case "$host" in *[!a-z0-9.-]*) return 1 ;; esac
    case ".$host." in *..*|*.-*|*-.*) return 1 ;; esac
    local IFS='.'
    for label in $host; do [ "${#label}" -le 63 ] || return 1; done
    PROBLEM='Use an address Nextcloud can reach: localhost points at the Nextcloud container itself.'
    case "$host" in localhost|127.*) return 1 ;; esac
    CLEAN="$host"
}

check_port() {
    PROBLEM='A port is a number from 1 to 65535.'
    [ -n "$1" ] && [ "${#1}" -le 5 ] || return 1
    case "$1" in *[!0-9]*) return 1 ;; esac
    local n=$((10#$1))
    [ "$n" -ge 1 ] && [ "$n" -le 65535 ] || return 1
    CLEAN="$n"
}

check_dir() {
    PROBLEM='Use letters, digits, dots, dashes and slashes, for example ./beeflow or /opt/beeflow.'
    [ -n "$1" ] && [ "${#1}" -le 200 ] || return 1
    case "$1" in *[!A-Za-z0-9._/~-]*) return 1 ;; esac
    case "/$1/" in */../*) return 1 ;; esac
    case "$1" in
        '~/'*) case "${1#'~/'}" in *'~'*) return 1 ;; esac ;;
        *'~'*) return 1 ;;
    esac
    CLEAN="$1"
}

check_version() {
    PROBLEM='Leave empty for the newest release, or enter a release tag such as v2026.11.10.3.'
    if [ -z "$1" ] || [ "$1" = latest ]; then CLEAN=latest; return 0; fi
    [ "${#1}" -le 40 ] || return 1
    case "$1" in v*) ;; *) return 1 ;; esac
    case "$1" in *[!A-Za-z0-9._-]*) return 1 ;; esac
    CLEAN="$1"
}

check_yes_no() {
    PROBLEM='Answer y or n.'
    case "${1,,}" in
        y|yes|1) CLEAN=1 ;;
        n|no|0) CLEAN=0 ;;
        *) return 1 ;;
    esac
}

check_organisation() {
    PROBLEM='Use up to 80 letters, digits and spaces.'
    [ "${#1}" -le 80 ] || return 1
    case "$1" in *[!A-Za-z0-9\ ._\&-]*) return 1 ;; esac
    CLEAN="$1"
}

check_organisation_named() {
    check_organisation "$1" || return 1
    PROBLEM='Enter the name of the organisation the code is for.'
    [ -n "$1" ]
}

check_stack_name() {
    PROBLEM='Lowercase letters, digits and dashes, not starting with a dash (leave empty for a single install).'
    [ "${#1}" -le 30 ] || return 1
    case "$1" in beeflow|-*|*[!a-z0-9-]*) return 1 ;; esac
    CLEAN="$1"
}

# Questions are read from the terminal device; where there is none (a
# container started with `docker run -it`), from standard input when that is a
# terminal.
TTY_OPEN=0
open_terminal() {
    if { : < "$TTY_DEVICE"; } 2>/dev/null; then
        exec 3< "$TTY_DEVICE"
    elif [ -t 0 ]; then
        exec 3<&0
    else
        die "There is no terminal to ask on. Give the answers as options or environment variables and add --yes (see --help)."
    fi
    TTY_OPEN=1
}

prompt() { # text → the line typed, in REPLY
    [ "$TTY_OPEN" = 1 ] || open_terminal
    printf '%s' "$1"
    IFS= read -r REPLY <&3 || die "No answer was given."
    REPLY="$(trim "$REPLY")"
}

# One answer: from an option or the environment when it was given there, the
# default with --yes, the terminal otherwise (asked again until it is usable).
ask() { # variable  question  default  shown-default  check
    local var="$1" question="$2" default="$3" shown="$4" check="$5" value
    if [ -n "${!var+x}" ]; then
        value="$(trim "${!var}")"
        "$check" "${value:-$default}" || die "$var: $PROBLEM"
    elif [ "$YES" = 1 ]; then
        "$check" "$default" || die "$var is needed with --yes. $PROBLEM"
    else
        while :; do
            prompt "$question${shown:+ [$shown]}: "
            if "$check" "${REPLY:-$default}"; then break; fi
            note "$PROBLEM"
        done
    fi
    printf -v "$var" '%s' "$CLEAN"
}

confirm() { # question  default (y|n)
    local shown='y/N'
    [ "$YES" = 1 ] && return 0
    [ "$2" = y ] && shown='Y/n'
    while :; do
        prompt "$1 [$shown]: "
        if check_yes_no "${REPLY:-$2}"; then break; fi
        note "$PROBLEM"
    done
    [ "$CLEAN" = 1 ]
}

ask_directory() {
    ask BEEFLOW_DIR 'Install directory' ./beeflow ./beeflow check_dir
    # A leading ~/ is the home directory.
    case "$BEEFLOW_DIR" in
        '~/'*) INSTALL_DIR="$HOME/${BEEFLOW_DIR#'~/'}" ;;
        *) INSTALL_DIR="$BEEFLOW_DIR" ;;
    esac
}

# With a bundle the version is the bundled one and is not asked.
ask_version() {
    if [ -z "$BUNDLE_DIR" ]; then
        ask BEEFLOW_VERSION 'Version (a release tag)' '' 'newest production release' check_version
        return 0
    fi
    local f
    if [ -z "$BUNDLE_VERSION" ] || [ "$BUNDLE_VERSION" = latest ] || ! check_version "$BUNDLE_VERSION"; then
        die "BEEFLOW_BUNDLE_VERSION must be the release tag of the files in $BUNDLE_DIR."
    fi
    for f in $RELEASE_FILES; do
        [ -f "$BUNDLE_DIR/$f" ] || die "$BUNDLE_DIR/$f is not there: the bundle is not complete."
    done
    if [ -n "${BEEFLOW_VERSION:-}" ] && [ "$BEEFLOW_VERSION" != "$BUNDLE_VERSION" ]; then
        note "This installer carries Bee Flow $BUNDLE_VERSION and installs or updates to that version only; the version $BEEFLOW_VERSION that was asked for is not used."
    fi
    BEEFLOW_VERSION="$BUNDLE_VERSION"
}

# The stack name, and what follows from it: the settings file and the names
# of the containers.
ask_stack_name() {
    if [ "$ADVANCED" = 1 ] || [ -n "${BEEFLOW_STACK_NAME+x}" ]; then
        ask BEEFLOW_STACK_NAME 'Stack name, for a second Bee Flow on this machine (empty = the single install)' '' '' check_stack_name
    else
        BEEFLOW_STACK_NAME=''
    fi
    STACK_NAME="$BEEFLOW_STACK_NAME"
    ENV_FILE=".env${STACK_NAME:+.$STACK_NAME}"
    STACK_LABEL="${STACK_NAME:-beeflow}"
    SERVER_CONTAINER="$STACK_LABEL-server"
    # How selfhost.sh is run for this stack, for the texts.
    SELFHOST="${STACK_NAME:+STACK_NAME=$STACK_NAME }./selfhost.sh"
}

# ── This machine ────────────────────────────────────────────────────────
need_tools() {
    command -v docker >/dev/null 2>&1 || die "Docker is not installed. See https://docs.docker.com/engine/install/"
    docker info >/dev/null 2>&1 || die "Docker is installed but this user cannot use it. Run this script as a user in the docker group, or with sudo."
    if ! docker compose version >/dev/null 2>&1 && ! command -v docker-compose >/dev/null 2>&1; then
        die "Docker Compose is missing. See https://docs.docker.com/compose/install/"
    fi
    command -v curl >/dev/null 2>&1 || die "curl is not installed."
}

need_amd64() {
    local arch
    arch="$(uname -m)"
    case "$arch" in
        x86_64|amd64) ;;
        *) die "This machine is $arch. The Bee Flow server images are published for x86-64 (amd64) only." ;;
    esac
}

port_in_use() { (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null; }

need_free_ports() {
    local p
    for p in "$SERVER_PORT" "$CLIENT_PORT"; do
        if port_in_use "$p"; then die "Port $p is already in use on this machine. Choose another port."; fi
    done
    [ "$BEEFLOW_SIDECARS" = 1 ] || return 0
    for p in $SIDECAR_PORTS; do
        if port_in_use "$p"; then
            die "Port $p is already in use on this machine. The PII guard and the topic classifier always use ports $SIDECAR_PORTS on 127.0.0.1; what holds port $p is probably another Bee Flow on this machine. Run this again and answer no to the guard and classifier (--no-sidecars), or share the other stack's sidecars: $MULTI_STACK_DOCS"
        fi
    done
}

# A warning, not a stop: the numbers are what is free right now.
warn_small_machine() {
    local need_gb=4 memory_kb disk_kb root
    [ "$BEEFLOW_SIDECARS" = 1 ] && need_gb=11
    memory_kb="$(sed -n 's/^MemAvailable:[[:space:]]*\([0-9][0-9]*\).*/\1/p' "$MEMINFO_FILE" 2>/dev/null | head -n1 || true)"
    if [ -n "$memory_kb" ] && [ "$memory_kb" -lt $((need_gb * 1024 * 1024)) ]; then
        warn "About $((memory_kb / 1024 / 1024)) GB of memory is free; this install wants about $need_gb GB (4 GB for Bee Flow itself, about 7 GB more with the PII guard and the topic classifier)."
    fi
    root="$(docker info --format '{{.DockerRootDir}}' 2>/dev/null || true)"
    [ -n "$root" ] && [ -d "$root" ] || root=/
    disk_kb="$(df -Pk "$root" 2>/dev/null | tail -n1 | tr -s ' ' | cut -d' ' -f4 || true)"
    case "$disk_kb" in ''|*[!0-9]*) return 0 ;; esac
    if [ "$disk_kb" -lt $((10 * 1024 * 1024)) ]; then
        warn "About $((disk_kb / 1024 / 1024)) GB of disk is free in $root; Bee Flow wants at least 10 GB."
    fi
}

# ── A release and its files ─────────────────────────────────────────────
# A GitHub releases listing on stdin → the tags of the product releases in it:
# the tag starts with v, and the release is not a draft and not a prerelease.
# (Other things are released from the same repository, so "the latest release"
# is not always a Bee Flow version.)
product_tags() {
    local line key val tag='' draft='' prerelease=''
    tr '{},' '\n\n\n' | { grep -E '^[[:space:]]*"(tag_name|draft|prerelease)"[[:space:]]*:' || true; } | while IFS= read -r line; do
        key="${line%%:*}"; key="${key//[[:space:]\"]/}"
        val="${line#*:}"; val="${val//[[:space:]\"]/}"
        case "$key" in
            tag_name) tag="$val"; draft=''; prerelease='' ;;
            draft) draft="$val" ;;
            prerelease) prerelease="$val" ;;
        esac
        [ -n "$tag" ] && [ -n "$draft" ] && [ -n "$prerelease" ] || continue
        if [ "$draft" = false ] && [ "$prerelease" = false ]; then
            case "$tag" in v*) printf '%s\n' "$tag" ;; esac
        fi
        tag=''
    done
}

# The release to use, in TAG: the given tag, or the newest production release.
resolve_release() { # version
    if [ "$1" != latest ]; then TAG="$1"; return 0; fi
    say "Looking up the newest Bee Flow release"
    TAG="$(curl -fsSL "$API_BASE/repos/$REPOSITORY/releases?per_page=30" | product_tags | sort -V | tail -n1 || true)"
    if [ -z "$TAG" ] || [ "$TAG" = latest ] || ! check_version "$TAG"; then
        die "Could not read the newest release from GitHub. Give a release tag with --version ($RELEASES_URL) and run this again."
    fi
}

drop_download() {
    local f
    for f in $RELEASE_FILES SHA256SUMS; do rm -f "$DOWNLOAD_DIR/$f"; done
    rmdir "$DOWNLOAD_DIR" 2>/dev/null || true
}

# The three downloaded files against the checksums of their release.
verify_download() { # tag
    local f sum='sha256sum'
    if ! command -v sha256sum >/dev/null 2>&1; then
        command -v shasum >/dev/null 2>&1 || { drop_download; die "sha256sum is not installed: the downloaded files cannot be checked."; }
        sum='shasum -a 256'
    fi
    for f in $RELEASE_FILES; do
        if ! grep -q "[ *]${f//./\\.}\$" "$DOWNLOAD_DIR/SHA256SUMS"; then
            drop_download
            die "The checksums of release $1 do not list $f. Nothing was changed."
        fi
    done
    if ! (cd "$DOWNLOAD_DIR" && $sum -c --ignore-missing SHA256SUMS >/dev/null 2>&1); then
        drop_download
        die "The downloaded files of release $1 do not match its checksums. Nothing was changed. Try again; if it happens again, report it: $RELEASES_URL"
    fi
    note "The files match the checksums of release $1."
}

# The installer files of a release into $DOWNLOAD_DIR (in the current
# directory), checked. A release from before the checksums has its files in
# the repository only; those cannot be checked, and that is said.
fetch_release() { # tag
    local f base="$DOWNLOAD_BASE/$1" checked=1
    mkdir -p "$DOWNLOAD_DIR"
    if [ -n "$BUNDLE_DIR" ]; then
        # They came with this installer: nothing to download, nothing to check.
        for f in $RELEASE_FILES; do cp "$BUNDLE_DIR/$f" "$DOWNLOAD_DIR/$f"; done
        note "The files of $1 that came with this installer are used ($BUNDLE_DIR)."
        return 0
    fi
    if ! curl -fsSL "$base/SHA256SUMS" -o "$DOWNLOAD_DIR/SHA256SUMS" 2>/dev/null; then
        checked=0
        base="$RAW_BASE/$REPOSITORY/$1"
        rm -f "$DOWNLOAD_DIR/SHA256SUMS"
        warn "Release $1 carries no checksums (it is from before this installer). Its files come from the repository and could NOT be checked."
    fi
    for f in $RELEASE_FILES; do
        if ! curl -fsSL "$base/$f" -o "$DOWNLOAD_DIR/$f"; then
            drop_download
            die "Could not download $f of release $1. Nothing was changed."
        fi
    done
    [ "$checked" = 0 ] || verify_download "$1"
}

# The fetched files into the current directory. With `keep`, a file that is
# replaced stays next to the new one as <name>.previous.
place_release() { # [keep]
    local f
    for f in $RELEASE_FILES; do
        if [ "${1:-}" = keep ] && [ -f "$f" ]; then cp -p "$f" "$f.previous"; fi
        mv "$DOWNLOAD_DIR/$f" "$f"
    done
    chmod +x selfhost.sh
    drop_download
}

# The last KEY= line of the settings file, without surrounding quotes.
value() { # key
    local v
    v="$( (grep -E "^$1=" "$ENV_FILE" || true) | tail -n1 | cut -d= -f2-)"
    v="${v%\"}"; v="${v#\"}"; v="${v%\'}"; v="${v#\'}"
    printf '%s' "$v"
}

# ── A pairing code ──────────────────────────────────────────────────────
# Signs in to the server as `admin` with the first password, from inside the
# server container, makes the organisation when it is not there, and asks for
# a code. Exit 3: the server refused the sign-in.
pairing_request() { # organisation  server port  web app address
    docker exec -i \
        -e BF_PASSWORD="$(value INIT_ADMIN_PASSWORD)" -e BF_ORGANISATION="$1" \
        -e BF_BASE="http://localhost:$2" -e BF_ORIGIN="$3" \
        "$SERVER_CONTAINER" node - <<'EOJS'
const { BF_PASSWORD, BF_ORGANISATION, BF_BASE, BF_ORIGIN } = process.env;
const fail = (what, code) => { console.error(what); process.exit(code || 1); };
const refused = (status) => (status === 401 || status === 403 ? 3 : 1);
(async () => {
    const login = await fetch(BF_BASE + '/auth/admin-login', {
        method: 'POST',
        headers: { 'content-type': 'application/json', origin: BF_ORIGIN },
        body: JSON.stringify({ username: 'admin', password: BF_PASSWORD }),
    });
    if (!login.ok) fail('sign-in as admin answered ' + login.status, 3);
    const cookie = (login.headers.getSetCookie() || []).map(c => c.split(';')[0]).join('; ');
    const call = async (method, path, body) => {
        const r = await fetch(BF_BASE + path, {
            method,
            headers: { 'content-type': 'application/json', origin: BF_ORIGIN, cookie },
            body: body ? JSON.stringify(body) : undefined,
        });
        return { status: r.status, json: await r.json().catch(() => ({})) };
    };
    const created = await call('POST', '/auth/organizations', { name: BF_ORGANISATION });
    let org = created.json.organization;
    if (!org) {
        const list = (await call('GET', '/auth/organizations')).json;
        org = (Array.isArray(list) ? list : (list.organizations || [])).find(o => o.name === BF_ORGANISATION);
    }
    if (!org) fail('the organisation could not be created (the server answered ' + created.status + ')', refused(created.status));
    const code = await call('POST', '/auth/admin/nc-bindings/generate-pairing-code', { organizationId: org.id });
    if (code.status !== 200 || !code.json.code) fail('the pairing code request answered ' + code.status, refused(code.status));
    console.log(code.json.code);
})().catch(e => fail(String(e && e.message || e)));
EOJS
}

# → PAIRING_CODE, or PAIRING_PROBLEM with why there is none.
make_pairing_code() { # organisation
    local out status=0 port protocol host
    port="$(value SERVER_PORT)"
    protocol="$(value CLIENT_PROTOCOL)"
    host="$(value CLIENT_PUBLIC_HOST)"
    PAIRING_CODE=''
    PAIRING_PROBLEM=''
    out="$(pairing_request "$1" "${port:-3001}" "${protocol:-http}://${host:-localhost:5176}" 2>&1)" || status=$?
    out="$(trim "${out##*$'\n'}")"
    if [ "$status" = 0 ] && [ -n "$out" ]; then
        PAIRING_CODE="$out"
    elif [ "$status" = 3 ]; then
        PAIRING_PROBLEM="The server refused the sign-in as admin: the first password was changed, or a second factor is on ($out)."
    else
        PAIRING_PROBLEM="The pairing code could not be made (${out:-no answer from the container $SERVER_CONTAINER})."
    fi
}

# Right after the first start the server answers on its port a little before
# its administrator account exists, and the sign-in is refused until then. The
# password cannot have been changed yet, so a refusal here means: not ready.
make_first_pairing_code() { # organisation
    local tries=0
    while :; do
        make_pairing_code "$1"
        [ -n "$PAIRING_CODE" ] && return 0
        tries=$((tries + 1))
        case "$PAIRING_PROBLEM" in "The server refused the sign-in"*) ;; *) return 0 ;; esac
        [ "$tries" -lt 12 ] || return 0
        sleep 5
    done
}

run_pairing-code() {
    ask_directory
    ask BEEFLOW_ORGANISATION 'Name of the organisation the code is for' '' '' check_organisation_named
    ask_stack_name
    need_tools
    [ -d "$INSTALL_DIR" ] || die "The directory $INSTALL_DIR is not there. Give the directory Bee Flow was installed in with --dir."
    cd "$INSTALL_DIR"
    [ -f "$ENV_FILE" ] || die "$(pwd)/$ENV_FILE is not there: no Bee Flow install was found in this directory."

    make_pairing_code "$BEEFLOW_ORGANISATION"
    if [ -z "$PAIRING_CODE" ]; then
        die "$PAIRING_PROBLEM Make the code in the web app instead: sign in, then $WHERE_TO_PAIR."
    fi
    say "Pairing code for \"$BEEFLOW_ORGANISATION\""
    note "$PAIRING_CODE   (valid for 15 minutes, works once)"
    note "In Nextcloud: open Bee Flow as an administrator and enter it as the pairing code."
}

# ── Install ─────────────────────────────────────────────────────────────
install_answers() {
    ask BEEFLOW_HOST 'Address of this Docker host, as Nextcloud reaches it (name or IP address)' '' '' check_host
    ask BEEFLOW_SERVER_PORT 'Server port' 3001 3001 check_port
    while :; do
        ask BEEFLOW_CLIENT_PORT 'Web app port' 5176 5176 check_port
        [ "$BEEFLOW_CLIENT_PORT" != "$BEEFLOW_SERVER_PORT" ] && break
        if [ "$YES" = 1 ] || [ -n "${CLIENT_PORT_GIVEN:-}" ]; then die "BEEFLOW_CLIENT_PORT: the server and the web app need two different ports."; fi
        note "The server and the web app need two different ports."
        unset BEEFLOW_CLIENT_PORT
    done
    ask_directory
    ask_version
    ask BEEFLOW_SIDECARS 'Also run the PII guard and the topic classifier (about 7 GB of memory)' y Y/n check_yes_no
    ask BEEFLOW_PRIVATE_NEXTCLOUD 'Is the Nextcloud on a private address (same machine or local network)' y Y/n check_yes_no
    ask BEEFLOW_ORGANISATION 'Name of your organisation, for a pairing code (empty = skip)' '' '' check_organisation
    ask_stack_name

    HOST="$BEEFLOW_HOST"
    SERVER_PORT="$BEEFLOW_SERVER_PORT"
    CLIENT_PORT="$BEEFLOW_CLIENT_PORT"
    ORGANISATION="$BEEFLOW_ORGANISATION"
    SERVER_URL="http://$HOST:$SERVER_PORT"
    WEB_URL="http://$HOST:$CLIENT_PORT"
    PROFILES='core'
    if [ "$BEEFLOW_SIDECARS" = 1 ]; then PROFILES='core guard classify'; fi
}

install_summary() {
    say "This will install Bee Flow on this machine"
    note "Directory:      $INSTALL_DIR"
    note "Version:        $([ "$BEEFLOW_VERSION" = latest ] && printf 'the newest production release' || printf '%s' "$BEEFLOW_VERSION")"
    note "Server:         $SERVER_URL"
    note "Web app:        $WEB_URL"
    note "Containers:     $PROFILES"
    note "Nextcloud:      $([ "$BEEFLOW_PRIVATE_NEXTCLOUD" = 1 ] && printf 'on a private address' || printf 'on a public address')"
    note "Organisation:   ${ORGANISATION:-none (no pairing code is made)}"
    [ -z "$STACK_NAME" ] || note "Stack name:     $STACK_NAME"
    if [ -n "$BUNDLE_DIR" ]; then
        note "It uses the installer files of that release that came with this installer and starts the containers."
    else
        note "It downloads the installer of that release from GitHub and starts the containers."
    fi
    note "Every secret is generated on this machine and shown at the end."
}

# selfhost.sh copies the template to the settings file and generates every
# secret itself, on this machine.
setting() { # key value
    grep -v "^$1=" .env.selfhost.example > .env.selfhost.example.tmp || true
    mv .env.selfhost.example.tmp .env.selfhost.example
    printf '%s=%s\n' "$1" "$2" >> .env.selfhost.example
}

write_settings() {
    setting TAG "$TAG"
    setting SERVER_PORT "$SERVER_PORT"
    setting CLIENT_PORT "$CLIENT_PORT"
    setting SERVER_PROTOCOL http
    setting CLIENT_PROTOCOL http
    setting SERVER_PUBLIC_HOST "$HOST:$SERVER_PORT"
    setting CLIENT_PUBLIC_HOST "$HOST:$CLIENT_PORT"
    # Published on every interface, so Nextcloud's connector can reach them.
    setting SERVER_BIND_HOST 0.0.0.0
    setting CLIENT_BIND_HOST 0.0.0.0
    if [ "$BEEFLOW_PRIVATE_NEXTCLOUD" = 1 ]; then setting NEXTCLOUD_ALLOW_PRIVATE_HOSTS 1; fi
}

# The server runs as uid 1000 and writes in the components directory. Made by
# root, that directory would be root's.
own_components() {
    [ "$(id -u)" = 0 ] || return 0
    local dir="components${STACK_NAME:+.$STACK_NAME}"
    mkdir -p "$dir"
    chown -R 1000:1000 "$dir"
}

start_stack() {
    export PROFILES
    if [ -n "$STACK_NAME" ]; then export STACK_NAME; fi
    say "Starting Bee Flow ($PROFILES). The first start downloads the images; with the PII guard that is several gigabytes."
    ./selfhost.sh
    own_components
    # A named stack stops once after writing its settings; the second run starts it.
    if [ -n "$STACK_NAME" ]; then ./selfhost.sh; fi

    # selfhost.sh has waited for the server already; this is the same check
    # on the port Nextcloud will use.
    local health="http://127.0.0.1:$SERVER_PORT/api/health"
    say "Checking that the server answers on port $SERVER_PORT"
    for _ in $(seq 1 90); do
        if curl -fsS "$health" >/dev/null 2>&1; then break; fi
        sleep 2
    done
    curl -fsS "$health" >/dev/null 2>&1 || die "The server does not answer on port $SERVER_PORT yet. Look at: $SELFHOST --logs"
}

# The guard and the classifier load their models at start. Wait for them, five
# minutes at most; the ones that are not ready by then are named in SIDECARS_NOT_READY.
wait_for_sidecars() {
    local name tries=0
    SIDECARS_NOT_READY=''
    [ "$BEEFLOW_SIDECARS" = 1 ] || return 0
    say "Waiting for the PII guard and the topic classifier (they load their models; a few minutes at most)"
    for name in "$STACK_LABEL-guard" "$STACK_LABEL-classify"; do
        until [ "$(docker inspect --format '{{.State.Health.Status}}' "$name" 2>/dev/null || true)" = healthy ]; do
            tries=$((tries + 1))
            if [ "$tries" -ge 60 ]; then SIDECARS_NOT_READY="$SIDECARS_NOT_READY $name"; break; fi
            sleep 5
        done
    done
}

install_report() {
    say "Bee Flow $TAG is installed. The addresses to use from Nextcloud and from other machines"
    note "(the localhost address printed above only works on this machine)"
    note "Web app:   $WEB_URL"
    note "Sign in:   admin / $(value INIT_ADMIN_PASSWORD)   (change it after the first sign-in)"
    if [ -n "$SIDECARS_NOT_READY" ]; then
        note "Not ready yet:$SIDECARS_NOT_READY. Bee Flow works without them meanwhile; they may need"
        note "more time or more memory. Look at: docker logs <name>"
    fi

    say "In Nextcloud: open Bee Flow, choose \"Self-hosted server\" and enter"
    note "Server URL:    $SERVER_URL"
    note "Web app URL:   $WEB_URL"
    if [ -n "$PAIRING_CODE" ]; then
        note "Pairing code:  $PAIRING_CODE   (valid for 15 minutes, works once)"
    elif [ -n "$PAIRING_PROBLEM" ]; then
        note "Pairing code:  NOT MADE. $PAIRING_PROBLEM"
        note "               Make it in the web app: sign in, then $WHERE_TO_PAIR."
        note "               Or try again: $SELF pairing-code --dir $(pwd)"
    else
        note "Pairing code:  sign in to the web app, create your organisation, then"
        note "               $WHERE_TO_PAIR"
    fi

    say "The secrets this install generated"
    note "They are in $(pwd)/$ENV_FILE (readable by you only). Keep a copy somewhere safe:"
    note "without MASTER_ENCRYPTION_KEY the stored data cannot be read again."
    local key
    for key in INIT_ADMIN_PASSWORD MASTER_ENCRYPTION_KEY SESSION_SECRET DB_PASSWORD RUSTFS_SECRET_KEY SERVICES_API_KEY; do
        printf '  %-22s %s\n' "$key" "$(value "$key")"
    done

    say "Later"
    note "Update:        $SELF update --dir $(pwd)${STACK_NAME:+ --stack-name $STACK_NAME}"
    note "Pairing code:  $SELF pairing-code --dir $(pwd)${STACK_NAME:+ --stack-name $STACK_NAME}"
    note "Logs:          cd $(pwd) && $SELFHOST --logs      Stop: $SELFHOST --stop"
    note "Ports $SERVER_PORT and $CLIENT_PORT are open on this machine's network interfaces, over plain http."
    note "For use outside your own network, put a reverse proxy with HTTPS in front."
}

run_install() {
    install_answers
    if [ -f "$INSTALL_DIR/$ENV_FILE" ]; then
        die "$INSTALL_DIR/$ENV_FILE exists: Bee Flow is already installed here. Update it with: $SELF update --dir $BEEFLOW_DIR   or choose another directory."
    fi
    install_summary
    confirm 'Continue?' y || { note "Nothing was changed."; exit 1; }

    need_tools
    need_amd64
    need_free_ports
    warn_small_machine
    resolve_release "$BEEFLOW_VERSION"
    note "Release: $TAG"

    mkdir -p "$INSTALL_DIR"
    cd "$INSTALL_DIR"
    say "The installer of $TAG, into $(pwd)"
    fetch_release "$TAG"
    place_release
    write_settings

    start_stack
    wait_for_sidecars
    PAIRING_CODE=''
    PAIRING_PROBLEM=''
    if [ -n "$ORGANISATION" ]; then
        say "Creating the organisation \"$ORGANISATION\" and a pairing code"
        make_first_pairing_code "$ORGANISATION"
    fi
    install_report
}

# ── Update ──────────────────────────────────────────────────────────────
# TAG=<value> as the last line of the settings file (no TAG line for an empty
# value); every other line, and the file's owner and mode, stay as they are.
set_tag() { # value
    local tmp="$ENV_FILE.tmp"
    ( umask 077; { grep -v '^TAG=' "$ENV_FILE" || true; } > "$tmp"; [ -z "$1" ] || printf 'TAG=%s\n' "$1" >> "$tmp" )
    cat "$tmp" > "$ENV_FILE"
    rm -f "$tmp"
}

# The image the server container runs; empty when there is no such container.
server_image() {
    docker inspect "$SERVER_CONTAINER" --format '{{.Config.Image}}' 2>/dev/null || true
}

# A version tag can be compared with another; a moving tag (latest, prod, no
# TAG at all) cannot.
is_version() { case "$1" in v*) return 0 ;; *) return 1 ;; esac; }

# Stops when the wanted release is older than the one in use.
refuse_older() { # current  wanted
    is_version "$1" || return 0
    [ "$(printf '%s\n%s\n' "$1" "$2" | sort -V | head -n1)" = "$2" ] || return 0
    die "This install is on $1 and $2 is older. Going back to an older release is not an update: see Rollback in $DOCS_UPGRADES"
}

update_plan() { # current  current image
    say "Update Bee Flow in $(pwd)"
    note "From:           ${1:-not pinned (no TAG in $ENV_FILE)}${2:+   (server image: $2)}"
    note "To:             $TAG"
    note "Release notes:  $RELEASES_URL"
    if ! is_version "$1"; then
        note "This install follows a moving tag, so its version cannot be compared with $TAG:"
        note "it may already run $TAG or something newer. Updating pins it to $TAG (TAG=$TAG in $ENV_FILE)."
    fi
    note "Make a backup first: the databases and the stored files. How: $DOCS_UPGRADES"
}

# The settings file and the installer files as they were before the update.
put_back() { # previous TAG
    local f
    set_tag "$1"
    for f in $RELEASE_FILES; do
        if [ -f "$f.previous" ]; then mv "$f.previous" "$f"; fi
    done
}

way_back() { # previous TAG  previous image
    say "The update did not finish. To go back to the previous version, in $(pwd):"
    if [ -n "$1" ]; then
        note "1. Put the previous version back in $ENV_FILE:   TAG=$1"
    else
        note "1. Take the line TAG=$TAG out of $ENV_FILE (there was none before)."
    fi
    [ -z "$2" ] || note "   (the server image this install was on: $2)"
    note "2. Restore the previous installer files:"
    note "     for f in $RELEASE_FILES; do [ -f \"\$f.previous\" ] && cp -p \"\$f.previous\" \"\$f\"; done"
    note "3. Run:   $SELFHOST --upgrade"
    note "Restore a database backup only when the release notes say so. More: $DOCS_UPGRADES"
}

run_update() {
    ask_directory
    ask_version
    ask_stack_name

    need_tools
    [ -d "$INSTALL_DIR" ] || die "The directory $INSTALL_DIR is not there. Give the directory Bee Flow was installed in with --dir."
    cd "$INSTALL_DIR"
    [ -f "$ENV_FILE" ] || die "$(pwd)/$ENV_FILE is not there: no Bee Flow install was found in this directory. Give its directory with --dir${STACK_NAME:+, and check the stack name}."
    [ -f selfhost.sh ] || die "$(pwd)/selfhost.sh is not there: this directory was not installed with the installer. See $DOCS_UPGRADES"

    # What runs now, recorded before anything changes.
    local current image
    current="$(value TAG)"
    image="$(server_image)"
    resolve_release "$BEEFLOW_VERSION"
    if [ "$current" = "$TAG" ]; then
        say "Bee Flow is already on $TAG. Nothing to do."
        exit 0
    fi
    refuse_older "$current" "$TAG"

    update_plan "$current" "$image"
    confirm "Update to $TAG now?" n || { note "Nothing was changed."; exit 1; }

    say "The installer of $TAG"
    fetch_release "$TAG"
    place_release keep
    set_tag "$TAG"

    if [ -n "$STACK_NAME" ]; then export STACK_NAME; fi
    say "Running ./selfhost.sh --upgrade"
    if ! ./selfhost.sh --upgrade; then
        # Still the same server image: the containers were not replaced.
        if [ -n "$image" ] && [ "$(server_image)" = "$image" ]; then
            put_back "$current"
            say "The update did not start: the server still runs $image."
            note "Nothing was changed: $ENV_FILE and the installer files are as they were (${current:-no TAG})."
        else
            way_back "$current" "$image"
        fi
        exit 1
    fi

    say "Bee Flow is now on $TAG"
    note "The Nextcloud connector needs nothing: it keeps its connection to this server."
    note "The previous installer files are kept next to the new ones as <name>.previous."
    if [ -z "$BUNDLE_DIR" ]; then
        note "This installer does not replace itself. The one of $TAG:"
        note "  curl -fsSLO $DOWNLOAD_BASE/$TAG/beeflow-install.sh"
    fi
}

