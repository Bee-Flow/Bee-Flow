case "${BEEFLOW_YES:-}" in 1|true|yes) YES=1 ;; esac
[ -z "${BEEFLOW_CLIENT_PORT+x}" ] || CLIENT_PORT_GIVEN=1

option_value() { # option  number of arguments left
    [ "$2" -ge 2 ] || die "$1 needs a value. See --help."
}

while [ "$#" -gt 0 ]; do
    case "$1" in
        install|update|pairing-code) MODE="$1" ;;
        -h|--help) usage; exit 0 ;;
        -y|--yes) YES=1 ;;
        --advanced) ADVANCED=1 ;;
        --host) option_value "$1" "$#"; BEEFLOW_HOST="$2"; shift ;;
        --server-port) option_value "$1" "$#"; BEEFLOW_SERVER_PORT="$2"; shift ;;
        --client-port) option_value "$1" "$#"; BEEFLOW_CLIENT_PORT="$2"; CLIENT_PORT_GIVEN=1; shift ;;
        --dir) option_value "$1" "$#"; BEEFLOW_DIR="$2"; shift ;;
        --version) option_value "$1" "$#"; BEEFLOW_VERSION="$2"; shift ;;
        --organisation) option_value "$1" "$#"; BEEFLOW_ORGANISATION="$2"; shift ;;
        --stack-name) option_value "$1" "$#"; BEEFLOW_STACK_NAME="$2"; shift ;;
        --sidecars) BEEFLOW_SIDECARS=1 ;;
        --no-sidecars) BEEFLOW_SIDECARS=0 ;;
        --private-nextcloud) BEEFLOW_PRIVATE_NEXTCLOUD=1 ;;
        --public-nextcloud) BEEFLOW_PRIVATE_NEXTCLOUD=0 ;;
        *) die "Unknown option: $1. See --help." ;;
    esac
    shift
done

