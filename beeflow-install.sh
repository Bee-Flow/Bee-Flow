#!/usr/bin/env bash
# ══════════════════════════════════════════════════════════════════
# Bee Flow: install or update a self-hosted Bee Flow with Docker.
#
#   bash beeflow-install.sh                install: asks a few questions, then starts Bee Flow
#   bash beeflow-install.sh update         update an install made with this script
#   bash beeflow-install.sh pairing-code   a fresh pairing code for a Nextcloud
#   bash beeflow-install.sh --help         every option
#
# The script is the same for everybody: it holds no answers and no secrets. It
# downloads the installer of a Bee Flow release (selfhost.sh, its compose file
# and its settings template) from GitHub, checks the files against the
# checksums of that release, writes your answers into the settings, and lets
# selfhost.sh do the work. Every secret is generated by selfhost.sh on this
# machine; this script generates none.
#
# Needs: bash 4+, docker with compose, curl.
# ══════════════════════════════════════════════════════════════════
set -euo pipefail
# Character classes below mean ASCII letters and digits, whatever the locale.
LC_ALL=C
export LC_ALL

REPOSITORY='Bee-Flow/Bee-Flow'
RELEASES_URL="https://github.com/$REPOSITORY/releases"
# Where releases are listed, where their files are, and where the files of a
# release from before the checksums are. The defaults are GitHub.
API_BASE="${BEEFLOW_API_BASE:-https://api.github.com}"
DOWNLOAD_BASE="${BEEFLOW_DOWNLOAD_BASE:-$RELEASES_URL/download}"
RAW_BASE="${BEEFLOW_RAW_BASE:-https://raw.githubusercontent.com}"
DOCS_UPGRADES='https://docs.beeflow.ai/self-hosting/upgrades'
MULTI_STACK_DOCS='https://docs.beeflow.ai/self-hosting/multi-stack'
RELEASE_FILES='selfhost.sh docker-compose.from-registry.yml .env.selfhost.example'
# A bundle: a directory that already holds the three files of one release (the
# installer image carries one). Then nothing is downloaded, and that release
# is the only one this run installs or updates to.
BUNDLE_DIR="${BEEFLOW_BUNDLE_DIR:-}"
BUNDLE_VERSION="${BEEFLOW_BUNDLE_VERSION:-}"
# Downloads land here, inside the install directory, until they are checked.
DOWNLOAD_DIR='.beeflow-download'
# The PII guard and the topic classifier publish these two ports on 127.0.0.1.
# They are fixed in the compose file of a release, not settings.
SIDECAR_PORTS="${BEEFLOW_SIDECAR_PORTS:-8100 8300}"
# How this installer was started, for the commands it prints (the installer
# image sets it to its docker run line).
SELF="${BEEFLOW_SELF_COMMAND:-bash beeflow-install.sh}"
# Where questions are read from (the terminal, also when the script is piped)
# and where the free memory is read from.
TTY_DEVICE="${BEEFLOW_TTY:-/dev/tty}"
MEMINFO_FILE="${BEEFLOW_MEMINFO:-/proc/meminfo}"
WHERE_TO_PAIR='Settings -> Organisation -> Pair a new Nextcloud'

say()  { printf '\n\033[1m%s\033[0m\n' "$*"; }
note() { printf '  %s\n' "$*"; }
warn() { printf '\n\033[33mWarning:\033[0m %s\n' "$*" >&2; }
die()  { printf '\n\033[31mStopped:\033[0m %s\n' "$*" >&2; exit 1; }

