/**
 * POST /api/install
 * Main installation endpoint.
 *
 * Builds all configuration as a JS environment object and passes it
 * directly to docker compose via the child process env -- no .env
 * file is written to disk.
 */
app.post('/api/install', (req, res) => {
    const parsed = InstallBody.safeParse(req.body || {});
    if (!parsed.success) {
        const issue = parsed.error.issues[0];
        return res.status(400).json({ success: false, error: `${issue.path.join('.')}: ${issue.message}` });
    }

    try {
        // ── 1–8. Secrets, compose env and profiles (lib/installPlan.js) ──
        const { secrets, configEnv, profiles } = buildInstallConfig(parsed.data, generateSecret);

        // ── 9. Build compose command (no --env-file) ─────────
        const profileFlags = profiles.map(p => `--profile ${p}`).join(' ');
        const composeCmd = `docker compose -f ${COMPOSE_FILE} ${profileFlags}`;

        // ── 10. Store env for status checks + save metadata ──
        currentEnv = { ...process.env, ...configEnv };

        // Persist configEnv so it survives wizard container restarts
        try {
            fs.writeFileSync(ENV_CACHE_PATH, JSON.stringify(configEnv), 'utf-8');
        } catch (e) {
            console.warn('[install] Could not persist env cache:', e.message);
        }

        const configPath = path.join(PROJECT_ROOT, '.install-config.json');
        fs.writeFileSync(configPath, JSON.stringify({
            profiles,
            composeCmd,
            timestamp: Date.now(),
        }), 'utf-8');

        // ── 11. System resource limits (cap at 80%) ──────────
        const os = require('os');
        const totalCpus = os.cpus().length;
        const buildCpus = Math.max(1, Math.floor(totalCpus * 0.80));
        const totalMemMB = Math.floor(os.totalmem() / 1024 / 1024);
        const buildMemMB = Math.floor(totalMemMB * 0.80);

        const buildEnv = {
            ...currentEnv,
            COMPOSE_DOCKER_CLI_BUILD: '1',
            DOCKER_BUILDKIT: '1',
            BUILDKIT_CPU_LIMIT: `${buildCpus}`,
            BUILDKIT_MEMORY_LIMIT: `${buildMemMB}m`,
        };

        // ── 12. Pull / build / up ─────────────────────────────
        const logFile = path.join(PROJECT_ROOT, '.install-log.txt');
        const logHeader =
            `[${new Date().toISOString()}] Starting deployment...\n` +
            `Mode: ${REGISTRY_MODE ? 'registry (pulling from Harbor)' : 'local build'}\n` +
            `Profiles: ${profiles.join(', ')}\n` +
            `Compose file: ${COMPOSE_FILE}\n` +
            `Resource limits: ${buildCpus}/${totalCpus} CPUs, ~80% of ${Math.floor(totalMemMB / 1024)}GB RAM\n\n`;
        fs.writeFileSync(logFile, logHeader, 'utf-8');
        console.log('[install] ' + logHeader.replace(/\n/g, ' | '));

        // In registry mode: docker login first, then pull (no build)
        const loginCmd = REGISTRY_MODE && REGISTRY_URL && REGISTRY_USER && REGISTRY_TOKEN
            ? `echo '${REGISTRY_TOKEN}' | docker login ${REGISTRY_URL} -u '${REGISTRY_USER}' --password-stdin && `
            : '';
        const upCmd = REGISTRY_MODE
            ? `${composeCmd} pull && ${composeCmd} up -d`
            : `${composeCmd} up -d --build`;
        const fullShCmd = `${loginCmd}${upCmd} 2>&1 | tee -a ${logFile}; echo "\n[INSTALL_COMPLETE]" >> ${logFile}`;

        console.log('[install] Registry mode:', REGISTRY_MODE);
        console.log('[install] Registry URL:', REGISTRY_URL || '(none)');
        console.log('[install] Compose file:', COMPOSE_FILE);
        console.log('[install] Profiles:', profiles.join(', '));
        console.log('[install] Running:', REGISTRY_MODE ? `pull + up` : 'build + up');
        console.log('[install] Command:', upCmd);

        const child = spawn('sh', ['-c', fullShCmd], {
            cwd: PROJECT_ROOT,
            detached: true,
            stdio: ['ignore', process.stdout, process.stderr],
            env: buildEnv,
        });
        child.unref();
        console.log('[install] Deploy process spawned (pid:', child.pid, ')');

        res.json({
            success: true,
            profiles,
            message: 'Deployment started! Check /api/status for progress.',
            secrets: {
                dbPassword:          secrets.DB_PASSWORD,
                sessionSecret:       secrets.SESSION_SECRET,
                masterEncryptionKey: secrets.MASTER_ENCRYPTION_KEY,
                servicesApiKey:      secrets.SERVICES_API_KEY,
            },
        });
    } catch (e) {
        // The operator running the wizard is its only caller, and a failed
        // write under /project is the diagnostic they need; the UI shows it.
        // eslint-disable-next-line no-restricted-syntax
        res.status(500).json({ success: false, error: e.message });
    }
});

/**
 * GET /api/status
 * Check deployment progress and container health.
 * Reuses the stored currentEnv so docker compose ps can resolve
 * mandatory ${VAR:?err} checks without a .env file.
 */
app.get('/api/status', (req, res) => {
    const logFile    = path.join(PROJECT_ROOT, '.install-log.txt');

    let logs = '';
    let complete = false;
    try {
        logs = fs.readFileSync(logFile, 'utf-8');
        complete = logs.includes('[INSTALL_COMPLETE]');
    } catch { /* no log yet */ }

    // Use stored env so mandatory compose vars are satisfied
    const psEnv = currentEnv || process.env;
    const ps = run(`docker compose -f ${COMPOSE_FILE} ps --format json 2>/dev/null`, { env: psEnv });
    let containers = [];
    if (ps.ok && ps.output) {
        try {
            containers = ps.output.split('\n')
                .filter(line => line.trim().startsWith('{'))
                .map(line => {
                    const c = JSON.parse(line);
                    return {
                        name:    c.Name    || c.Service,
                        service: c.Service,
                        state:   c.State,
                        status:  c.Status,
                        health:  c.Health || '',
                    };
                });
        } catch { /* parse error, ignore */ }
    }

    res.json({
        deploying: !complete,
        complete,
        logs: logs.slice(-5000), // last 5 KB
        containers,
    });
});

