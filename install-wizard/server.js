/**
 * BeeFlow Install Wizard -- Backend Server
 *
 * Lightweight Express server that:
 * - Serves the wizard UI (static files)
 * - Detects GPU availability
 * - Builds config env vars and deploys containers
 * - Orchestrates container deployment via Docker socket
 *
 * All configuration is passed as environment variables directly
 * to the docker compose child process -- no .env file is written.
 */

