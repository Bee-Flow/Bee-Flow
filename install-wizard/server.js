// ── Helpers ─────────────────────────────────────────────────────

function generateSecret(length = 32) {
    return crypto.randomBytes(length).toString('hex');
}

function run(cmd, opts = {}) {
    try {
        return { ok: true, output: execSync(cmd, { encoding: 'utf-8', timeout: 30000, ...opts }).trim() };
    } catch (e) {
        return { ok: false, output: e.stderr || e.message };
    }
}

// ── In-memory env store ──────────────────────────────────────────
// Holds the full config env built during /api/install so that
// /api/status can reuse it when calling docker compose ps
// (which needs vars like DB_PASSWORD for the mandatory checks).
let currentEnv = null;

// Restore env from previous install (survives wizard container restarts)
const ENV_CACHE_PATH = path.join(PROJECT_ROOT, '.install-env.json');
try {
    if (fs.existsSync(ENV_CACHE_PATH)) {
        const saved = JSON.parse(fs.readFileSync(ENV_CACHE_PATH, 'utf-8'));
        currentEnv = { ...process.env, ...saved };
        console.log('[boot] Restored env from previous install (%d vars)', Object.keys(saved).length);
    }
} catch (e) {
    console.warn('[boot] Could not restore saved env:', e.message);
}

