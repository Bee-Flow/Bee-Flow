/**
 * GET /api/detect-gpu
 * Check if NVIDIA GPU runtime is available in Docker
 */
app.get('/api/detect-gpu', (req, res) => {
    const dockerInfo = run('docker info --format "{{json .Runtimes}}" 2>/dev/null');
    const hasNvidiaRuntime = dockerInfo.ok && dockerInfo.output.includes('nvidia');

    let gpuName = '';
    let gpuMemory = '';
    if (hasNvidiaRuntime) {
        const smi = run('docker run --rm --gpus all nvidia/cuda:12.0.0-base-ubuntu22.04 nvidia-smi --query-gpu=name,memory.total --format=csv,noheader 2>/dev/null');
        if (smi.ok && smi.output) {
            const parts = smi.output.split(',').map(s => s.trim());
            gpuName = parts[0] || '';
            gpuMemory = parts[1] || '';
        }
    }

    res.json({
        available: hasNvidiaRuntime,
        gpuName,
        gpuMemory,
        message: hasNvidiaRuntime
            ? `GPU detected: ${gpuName} (${gpuMemory})`
            : 'No NVIDIA GPU runtime found in Docker. GPU services will be unavailable.',
    });
});

