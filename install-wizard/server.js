/**
 * GET /api/running-services
 * Returns which BeeFlow services are currently running.
 * Used by the wizard to detect if there's an existing installation to update.
 */
app.get('/api/running-services', (req, res) => {
    const ps = run(
        'docker ps --filter "name=beeflow" --filter "name=search-api" ' +
        '--filter "name=search-postgres" --filter "name=search-redis" ' +
        '--filter "name=guard" --filter "name=whisperx" ' +
        '--format "{{json .}}" 2>/dev/null'
    );

    const containers = [];
    if (ps.ok && ps.output) {
        for (const line of ps.output.split('\n')) {
            const t = line.trim();
            if (!t || !t.startsWith('{')) continue;
            try {
                const c = JSON.parse(t);
                containers.push({
                    name:   c.Names || c.Name,
                    image:  c.Image,
                    state:  c.State,
                    status: c.Status,
                });
            } catch { /* skip */ }
        }
    }

    // Also check if a saved install config exists
    const configPath = path.join(PROJECT_ROOT, '.install-config.json');
    let savedConfig = null;
    try { savedConfig = JSON.parse(fs.readFileSync(configPath, 'utf-8')); } catch { /* none */ }

    res.json({ containers, savedConfig, registryMode: REGISTRY_MODE });
});

 /**
 * GET /api/check-updates
 * Compare local image digests against Harbor registry manifests.
 * Also checks the wizard's own image for self-update detection.
 */
app.get('/api/check-updates', async (req, res) => {
    if (!REGISTRY_MODE || !REGISTRY_URL || !REGISTRY_TOKEN) {
        return res.json({ available: false, reason: 'Registry mode not configured', services: [] });
    }

    const SERVICE_MAP = {
        'beeflow-wizard':          'beeflow/install-wizard',
        'beeflow-server':          'beeflow/server',
        'beeflow-agent-hub':       'beeflow/agent-hub',
        'search-api':              'beeflow/search-api',
        'search-inference-gpu':    'beeflow/search-inference-gpu',
        'beeflow-guard':           'beeflow/guard-service',
        'whisperx-service':        'beeflow/whisperx',
        'beeflow-pii':             'beeflow/pii-service',
    };

    // Get running containers
    const ps = run(
        'docker ps --filter "name=beeflow" --filter "name=search-api" ' +
        '--filter "name=search-inference-gpu" --filter "name=guard" ' +
        '--filter "name=whisperx" --format "{{json .}}" 2>/dev/null'
    );
    const running = [];
    if (ps.ok && ps.output) {
        for (const line of ps.output.split('\n')) {
            const t = line.trim();
            if (!t || !t.startsWith('{')) continue;
            try { running.push(JSON.parse(t)); } catch { /* skip */ }
        }
    }

    // ── Helper: local digest ─────────────────────────────────────
    function getLocalDigest(containerName) {
        // Step 1: Get the image reference the container was started with
        const imgRef = run(`docker inspect "${containerName}" --format "{{.Config.Image}}" 2>/dev/null`);
        if (!imgRef.ok || !imgRef.output) return { digest: null, error: 'container not found' };

        const imageName = imgRef.output.trim();
        // Parse repo + tag from "repo:tag" or "repo" (implies :latest)
        const colonIdx = imageName.lastIndexOf(':');
        const imgRepo = colonIdx > 0 ? imageName.substring(0, colonIdx) : imageName;
        const imgTag  = colonIdx > 0 ? imageName.substring(colonIdx + 1) : 'latest';

        // Step 2: Try `docker images --digests` — most reliable for pulled images
        const digestTable = run(`docker images --no-trunc --digests --format "{{.Repository}}\t{{.Tag}}\t{{.Digest}}" 2>/dev/null`);
        if (digestTable.ok && digestTable.output) {
            for (const line of digestTable.output.split('\n')) {
                const parts = line.trim().split('\t');
                if (parts.length < 3) continue;
                const [repo, tag, digest] = parts;
                if (repo === imgRepo && tag === imgTag && digest && digest !== '<none>') {
                    return { digest, imageName };
                }
            }
        }

        // Step 3: Fallback — inspect image by ID, read RepoDigests
        const imageId = run(`docker inspect "${containerName}" --format "{{.Image}}" 2>/dev/null`);
        if (!imageId.ok || !imageId.output) return { digest: null, error: 'image id not found', imageName };

        const digests = run(`docker image inspect "${imageId.output.trim()}" --format "{{json .RepoDigests}}" 2>/dev/null`);
        if (!digests.ok || !digests.output) return { digest: null, error: 'no RepoDigests', imageName };

        try {
            const arr = JSON.parse(digests.output);
            for (const d of arr) {
                const match = d.match(/@(sha256:[a-f0-9]+)/);
                if (match) return { digest: match[1], imageName };
            }
        } catch { /* skip */ }

        return { digest: null, error: 'empty RepoDigests (locally built image)', imageName };
    }

    // ── Helper: remote manifest digest ──────────────────────────
    // Verified TLS only, and the credentials never go over plain HTTP; see
    // lib/registryDigest.js for the two opt-ins.
    const getRemoteDigest = createRemoteDigest({
        registryUrl: REGISTRY_URL,
        user: REGISTRY_USER,
        token: REGISTRY_TOKEN,
        ...REGISTRY_TRANSPORT,
    });

    // ── Run checks ───────────────────────────────────────────────
    const checks = await Promise.all(
        running
            .filter(c => SERVICE_MAP[c.Names || c.Name])
            .map(async (c) => {
                const name = c.Names || c.Name;
                const repo = SERVICE_MAP[name];
                const local = getLocalDigest(name);
                const remote = await getRemoteDigest(repo);
                const hasUpdate = !!(remote.digest && local.digest && remote.digest !== local.digest);
                const isUnknown = !local.digest || !remote.digest;
                return {
                    name,
                    repo,
                    localDigest:    local.digest,
                    remoteDigest:   remote.digest,
                    hasUpdate,
                    isUnknown,
                    localError:     local.error  || null,
                    remoteError:    remote.error || null,
                    registryStatus: remote.status,
                };
            })
    );

    const anyUpdate  = checks.some(c => c.hasUpdate);
    const wizardSelf = checks.find(c => c.name === (process.env.CONTAINER_NAME || 'beeflow-wizard'));
    res.json({ available: anyUpdate, wizardHasUpdate: wizardSelf?.hasUpdate || false, services: checks });
});

/**
 * POST /api/self-update
 * Pull a newer wizard image from Harbor and restart this container.
 * Spawns a detached shell (waits 2s so HTTP response can be sent first).
 */
app.post('/api/self-update', (req, res) => {
    if (!REGISTRY_MODE || !REGISTRY_URL || !REGISTRY_TOKEN) {
        return res.status(400).json({ error: 'Registry mode not configured' });
    }

    const myName  = process.env.CONTAINER_NAME || 'beeflow-wizard';
    const myPort  = process.env.WIZARD_PORT    || '9090';
    const composeFileName = path.basename(COMPOSE_FILE);
    const wizardImage = `${REGISTRY_URL}/beeflow/install-wizard:latest`;

    const runArgs = [
        `--name ${myName}`,
        `-p ${myPort}:9090`,
        `-v /var/run/docker.sock:/var/run/docker.sock`,
        `-v ${PROJECT_ROOT}:/project`,
        `-e REGISTRY_MODE=1`,
        `-e REGISTRY_URL='${REGISTRY_URL}'`,
        `-e REGISTRY_USER='${REGISTRY_USER}'`,
        `-e REGISTRY_TOKEN='${REGISTRY_TOKEN}'`,
        `-e COMPOSE_FILE='${composeFileName}'`,
        `-e CONTAINER_NAME='${myName}'`,
        `-e WIZARD_PORT='${myPort}'`,
        // Keep the operator's transport opt-ins across the restart.
        ...(REGISTRY_TRANSPORT.insecureTls ? ['-e REGISTRY_INSECURE_TLS=1'] : []),
        ...(REGISTRY_TRANSPORT.allowHttp ? ['-e REGISTRY_ALLOW_HTTP=1'] : []),
        `--restart unless-stopped`,
    ].join(' ');

    const script = [
        `sleep 2`,
        `echo '${REGISTRY_TOKEN}' | docker login ${REGISTRY_URL} -u '${REGISTRY_USER}' --password-stdin`,
        `docker pull ${wizardImage}`,
        `docker rm -f ${myName}`,
        `docker run -d ${runArgs} ${wizardImage}`,
    ].join(' && ');

    const child = spawn('sh', ['-c', script], { detached: true, stdio: 'ignore' });
    child.unref();

    res.json({ success: true, message: 'Self-update in progress. Reconnect in ~5 seconds.' });
});

