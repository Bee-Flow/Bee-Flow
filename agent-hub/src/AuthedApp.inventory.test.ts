// @vitest-environment node
/**
 * GUI inventory: the providers and overlays that wrap the whole signed-in app
 * (AuthedApp.tsx), read with the TypeScript compiler API: the component tree
 * each of its three render functions returns (AuthedApp, App,
 * AppRecorderProvider), outermost first. Per component: its place, nesting
 * depth (HTML elements add none), the condition it renders under
 * (`isAuthenticated && <CaptureModal />`), the file it is imported or
 * lazy-loaded from, and that file's owner. Plus the lazy imports of the file,
 * so a screen it loads for a page (`if (page === 'admin')`) is listed too.
 *
 * Plan phase 2.2 replaces the module-owned providers and overlays here with two
 * slots; with every module present this golden must not change.
 * Regenerate: UPDATE_GOLDEN=1 npx vitest run src/AuthedApp.inventory.test.ts
 */
import { describe, expect, it } from 'vitest';
import { checkGolden } from '@/test/guiInventory/golden';
import { ownersOf } from '@/test/guiInventory/ownership';
import { jsxTree, loadSource } from '@/test/guiInventory/sourceAst';

const COMMENT = 'Generated by AuthedApp.inventory.test.ts (UPDATE_GOLDEN=1). `tree`: per render function of AuthedApp.tsx, '
    + 'the components it returns, outermost first, with depth, condition, file and owner. `lazy`: every lazy import of the '
    + 'file in source order (name, file, owner).';

describe('AuthedApp providers and overlays inventory', () => {
    it('matches the golden', () => {
        const app = loadSource('src/AuthedApp.tsx');
        const tree = ['AuthedApp', 'App', 'AppRecorderProvider'].flatMap((fn) => jsxTree(app, fn)
            .map((n, position) => ({ in: fn, position, ...n, owner: ownersOf([n.file]) })));
        const lazy = [...app.lazies].map(([name, file], position) => ({ position, name, file, owner: ownersOf([file]) }));
        expect(tree.some((n) => n.tag === 'RecorderProvider')).toBe(true);
        checkGolden(import.meta.url, COMMENT, { tree, lazy });
    });
});
