// @vitest-environment node
/**
 * GUI inventory: the lazy slots of the hub (hubLazySlots.tsx), the screens
 * AgentHub opens in its main column and its modal slots. Per slot, read with
 * the TypeScript compiler API: its place, export name, the tree path of the
 * file its `lazy(() => import('…'))` loads and that file's owner; and the
 * branch of HubMainContent.tsx (`currentPage === 'cowork'`, `showStudio`) that
 * renders it, where one does.
 *
 * Regenerate: UPDATE_GOLDEN=1 npx vitest run src/AgentHub/hubLazySlots.inventory.test.ts
 */
import { describe, expect, it } from 'vitest';
import { checkGolden } from '@/test/guiInventory/golden';
import { ownersOf } from '@/test/guiInventory/ownership';
import { pageScreens } from '@/test/guiInventory/pages';
import { loadSource } from '@/test/guiInventory/sourceAst';

const COMMENT = 'Generated by AgentHub/hubLazySlots.inventory.test.ts (UPDATE_GOLDEN=1). `slots`: every lazy export of '
    + 'hubLazySlots.tsx in source order, the file it loads, its owner, and the page keys whose branch renders it.';

describe('hub lazy slots inventory', () => {
    it('matches the golden', () => {
        const slots = [...loadSource('src/AgentHub/hubLazySlots.tsx').lazies].map(([name, file], position) => ({
            position,
            name,
            component: file,
            owner: ownersOf([file]),
            pages: [...pageScreens()].filter(([, refs]) => refs.some((r) => r.name === name)).map(([page]) => page),
        }));
        expect(slots.length).toBeGreaterThanOrEqual(10);
        checkGolden(import.meta.url, COMMENT, { slots });
    });
});
