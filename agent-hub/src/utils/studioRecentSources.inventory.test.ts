// @vitest-environment node
/**
 * GUI inventory: the "recently worked on" sources of the Studio flyout
 * (studioRecentSources.ts STUDIO_RECENT_SOURCES), recorded from the running
 * table. Per source: its place, the Studio section id, the list endpoint,
 * whether it answers a status, and the screen of that section
 * (components/admin/Studio/studioRegistry.tsx, read with the TypeScript compiler
 * API) with its owner.
 *
 * Regenerate: UPDATE_GOLDEN=1 npx vitest run src/utils/studioRecentSources.inventory.test.ts
 */
import { describe, expect, it } from 'vitest';
import { checkGolden } from '@/test/guiInventory/golden';
import { ownersOf } from '@/test/guiInventory/ownership';
import { loadSource } from '@/test/guiInventory/sourceAst';
import { STUDIO_RECENT_SOURCES } from './studioRecentSources';

const registry = loadSource('src/components/admin/Studio/studioRegistry.tsx');

const COMMENT = 'Generated by utils/studioRecentSources.inventory.test.ts (UPDATE_GOLDEN=1). `sources`: STUDIO_RECENT_SOURCES in '
    + 'order: section id, endpoint, whether it has a status accessor, and the section\'s screen (file, owner).';

describe('Studio recent sources inventory', () => {
    it('matches the golden', () => {
        const sources = Object.entries(STUDIO_RECENT_SOURCES).map(([id, s], position) => {
            const component = registry.lazies.get(id) ?? null;
            return { position, id, url: s.url, status: typeof s.status === 'function', component, owner: ownersOf([component]) };
        });
        expect(sources.length).toBeGreaterThanOrEqual(9);
        checkGolden(import.meta.url, COMMENT, { sources });
    });
});
