import React, { useCallback, useEffect, useState } from 'react';
import { AlertCircle, Newspaper, RefreshCw } from 'lucide-react';
import { API_BASE } from '@/utils/helpers';
import { settled } from '@/api/settled';
import { useTranslation } from '@/hooks/useTranslation';
import { messageOf } from '@/utils/caughtError';
import { request, RefusedError } from '@/api/mutate';
import ReleaseNoteCard from './ReleaseNoteCard';
import type { ReleaseNoteEntry } from './ReleaseNoteCard';
import EmptyState from '@/components/shared/EmptyState';
import SectionHeader from '@/components/shared/SectionHeader';
import Spinner from '@/components/shared/Spinner';
import { ALERT_ERROR, SECONDARY_BTN } from '@/components/mcpLibrary/ui';

/**
 * Release notes review queue — the human gate.
 *
 * The build pipeline drafts notes on every dev and prod build and files them as
 * `draft`. Nothing here is public until someone presses Publish, which is the
 * entire point: the copy is machine-written and a customer should never be the
 * first human to read it.
 *
 * The rolling "Unreleased" entry (no version) is regenerated by each dev build,
 * so edits to it are provisional — the store refuses to overwrite it once it has
 * been published, but an unpublished edit will be replaced by the next build.
 * The panel says so rather than letting someone lose work silently.
 */

export default function ReleaseNotesPanel() {
    const { t } = useTranslation();
    const [entries, setEntries] = useState<ReleaseNoteEntry[]>([]);
    const [loading, setLoading] = useState(true);
    const [busyId, setBusyId] = useState<string | null>(null);
    const [error, setError] = useState('');

    const load = useCallback(async () => {
        setLoading(true);
        setError('');
        try {
            let res: Response;
            try {
                res = await request(`${API_BASE}/api/release-notes/admin`);
            } catch (err) {
                if (!(err instanceof RefusedError)) throw err;
                throw new Error(`Request failed (${err.status})`);
            }
            const data = await res.json();
            setEntries(Array.isArray(data.entries) ? data.entries : []);
        } catch (e) {
            setError(messageOf(e, 'Could not load release notes'));
        }
        setLoading(false);
    }, []);

    useEffect(() => { load(); }, [load]);

    const act = async (id: string, path: string, method = 'POST', body?: Record<string, string>) => {
        setBusyId(id);
        setError('');
        try {
            const res = await settled(`${API_BASE}/api/release-notes/admin/${id}${path}`, {
                method,
                ...(body ? { headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) } : {}),
            }, 'empty');
            if (!res.ok) throw new Error(`Request failed (${res.status})`);
            await load();
        } catch (e) {
            setError(messageOf(e, 'Action failed'));
        }
        setBusyId(null);
    };

    const patch = (id: string, fields: Record<string, string>) => act(id, '', 'PUT', fields);

    const edit = (id: string, fields: Partial<Pick<ReleaseNoteEntry, 'title' | 'lead'>>) =>
        setEntries(prev => prev.map(x => x.id === id ? { ...x, ...fields } : x));

    if (loading) {
        return (
            <div className="flex items-center gap-2 text-sm text-[var(--text-secondary)]">
                <Spinner size="sm" /> {t('cms_site.site.releasenotes.loading', 'Loading release notes…')}
            </div>
        );
    }

    return (
        <div className="flex max-w-4xl flex-col gap-4">
            <SectionHeader
                title={t('cms_site.site.releasenotes.title', 'Release notes')}
                description={t('cms_site.site.releasenotes.intro', 'Drafted automatically on every build. Nothing appears on the website until you publish it.')}
                status={(
                    <button type="button" onClick={load} className={SECONDARY_BTN}>
                        <RefreshCw className="h-3.5 w-3.5" aria-hidden="true" /> {t('cms_site.site.releasenotes.refresh', 'Refresh')}
                    </button>
                )}
            />

            {error ? (
                <div className={ALERT_ERROR} role="alert">
                    <AlertCircle className="mt-0.5 h-4 w-4 shrink-0" aria-hidden="true" />
                    <span>{error}</span>
                </div>
            ) : null}

            {entries.length === 0 ? (
                <EmptyState
                    className="h-auto rounded-lg border border-dashed border-[var(--border-default)]"
                    icon={<Newspaper className="h-8 w-8" strokeWidth={1.5} />}
                    title={t('cms_site.site.releasenotes.title', 'Release notes')}
                    description={t('cms_site.site.releasenotes.empty', 'No release notes yet. They appear here after the next build.')}
                />
            ) : null}

            <div className="flex flex-col gap-4">
                {entries.map(entry => (
                    <ReleaseNoteCard key={entry.id} entry={entry} busy={busyId === entry.id} onAct={act} onEdit={edit} onSave={patch} />
                ))}
            </div>
        </div>
    );
}
