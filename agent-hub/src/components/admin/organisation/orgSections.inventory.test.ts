// @vitest-environment node
/**
 * GUI inventory: the Organisation tab of the admin dashboard (orgSections.ts
 * ORG_HUB_SECTIONS), recorded from the running list. Per section: its place,
 * id, rail group, i18n label key, icon, its visibility rule as run
 * (isOrgSectionVisible on a recording set of facts, test/guiInventory/gates.ts),
 * and the panel that draws it: OrgSectionBody.tsx DIRECT_PANELS, else
 * pages/settings/OrganisationSection.tsx ORG_ADMIN_PAGES under the Settings id
 * (both read with the TypeScript compiler API), with the owner of that panel.
 *
 * Regenerate: UPDATE_GOLDEN=1 npx vitest run src/components/admin/organisation/orgSections.inventory.test.ts
 */
import { describe, expect, it } from 'vitest';
import { checkGolden } from '@/test/guiInventory/golden';
import { probeGate } from '@/test/guiInventory/gates';
import { iconName } from '@/test/guiInventory/icons';
import { ownersOf } from '@/test/guiInventory/ownership';
import { loadSource, objectMapRefs, stringMap, type ComponentRef } from '@/test/guiInventory/sourceAst';
import { ORG_HUB_SECTIONS, isOrgSectionVisible } from './orgSections';

const BODY = loadSource('src/components/admin/organisation/OrgSectionBody.tsx');
const direct = new Map(objectMapRefs(BODY, 'DIRECT_PANELS').map((p) => [p.key, p.components]));
const settingsIds = stringMap(BODY, 'SETTINGS_SECTION_IDS');
const orgPages = new Map(objectMapRefs(loadSource('src/pages/settings/OrganisationSection.tsx'), 'ORG_ADMIN_PAGES').map((p) => [p.key, p.components]));

/** The panel of a section, as OrgSectionBody SectionPanel picks it. */
function panelOf(id: string): { via: string; components: ComponentRef[] } {
    const own = direct.get(id);
    if (own) return { via: 'OrgSectionBody.DIRECT_PANELS', components: own };
    const settingsId = settingsIds[id] ?? id.replaceAll('-', '_');
    return { via: `OrganisationSection:${settingsId}`, components: orgPages.get(settingsId) ?? [] };
}

const COMMENT = 'Generated by components/admin/organisation/orgSections.inventory.test.ts (UPDATE_GOLDEN=1). `sections`: '
    + 'ORG_HUB_SECTIONS in order with the visibility rule as run (a list is an AND of facts), the panel (`via`: '
    + 'OrgSectionBody DIRECT_PANELS, or OrganisationSection under the Settings id; an OrganisationSection id without a '
    + 'page of its own is drawn by its info form, OrgInfoPanel) and its owner.';

describe('organisation sections inventory', () => {
    it('matches the golden', () => {
        const sections = ORG_HUB_SECTIONS.map((s, position) => {
            const panel = panelOf(s.id);
            const files = panel.components.map((c) => c.file).filter((f): f is string => !!f);
            return {
                position, id: s.id, group: s.group, labelKey: s.labelKey, labelFallback: s.labelFallback, descriptionKey: s.descriptionKey,
                icon: iconName(s.icon, ['src/components/admin/organisation/orgSections.ts']),
                visibleWhen: probeGate((f: never) => isOrgSectionVisible(s.id, f)),
                via: panel.via, components: files, owner: ownersOf(files.length ? files : ['src/pages/settings/OrganisationSection.tsx']),
            };
        });
        expect(sections.length).toBeGreaterThanOrEqual(19);
        checkGolden(import.meta.url, COMMENT, { sections });
    });
});
