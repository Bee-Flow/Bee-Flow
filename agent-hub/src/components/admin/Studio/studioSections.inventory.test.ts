/**
 * GUI inventory: the Studio sections (studioSections.ts STUDIO_SECTIONS, the
 * start page STUDIO_START_SECTION and the headings STUDIO_CATEGORIES of
 * studioGates.ts), recorded from the running registry. Per section: its place,
 * address, label, icon, kind, every gate (the gate function is run, see
 * test/guiInventory/gates.ts), its "New" entry, and the screen studioRegistry.tsx
 * loads for it (its lazy import, read with the TypeScript compiler API) with
 * that screen's owner in the ownership map.
 *
 * mobile/src/features/studio/model/studioSections.lockstep.test.ts reads the
 * golden. Regenerate: UPDATE_GOLDEN=1 npx vitest run src/components/admin/Studio/studioSections.inventory.test.ts
 */
import { describe, expect, it } from 'vitest';
import { checkGolden } from '@/test/guiInventory/golden';
import { probeGate } from '@/test/guiInventory/gates';
import { iconName } from '@/test/guiInventory/icons';
import { ownersOf } from '@/test/guiInventory/ownership';
import { loadSource } from '@/test/guiInventory/sourceAst';
import { STUDIO_CATEGORIES } from './studioGates';
import { STUDIO_SECTIONS, STUDIO_START_SECTION, type StudioStartDescriptor } from './studioSections';

const GATE_CTX = { calls: ['hasLicenseFeature', 'hasPermission', 'canUse', 'can', 'lockReason'] } as const;

const SECTIONS_FILE = 'src/components/admin/Studio/studioSections.ts';
const registry = loadSource('src/components/admin/Studio/studioRegistry.tsx');

function sectionRow(s: StudioStartDescriptor, position: number) {
    const component = registry.lazies.get(s.id) ?? null;
    return {
        position,
        id: s.id,
        urlSegment: s.urlSegment,
        legacySegments: s.legacySegments ? [...s.legacySegments] : undefined,
        category: s.category,
        labelKey: s.labelKey,
        labelFallback: s.labelFallback,
        descKey: s.descKey,
        descFallback: s.descFallback,
        icon: iconName(s.Icon, [SECTIONS_FILE]),
        kind: s.kind,
        countKey: s.countKey,
        hiddenFromNav: s.hiddenFromNav,
        topLevelEntrance: s.topLevelEntrance,
        moduleId: s.moduleId,
        trainingArea: (s as { trainingArea?: string }).trainingArea,
        gate: probeGate(s.gate as (ctx: never) => unknown, GATE_CTX),
        permission: s.permission,
        gateCapability: s.gateCapability,
        lockOn: s.lockOn,
        create: s.create ? { labelKey: s.create.labelKey, labelFallback: s.create.labelFallback, kind: s.create.kind } : undefined,
        component,
        owner: ownersOf([component]),
    };
}

const COMMENT = 'Generated by components/admin/Studio/studioSections.inventory.test.ts (UPDATE_GOLDEN=1). '
    + '`sections`: STUDIO_SECTIONS in order, each with its gate as run (test/guiInventory/gates.ts: a list is an AND of legs), '
    + 'the screen studioRegistry.tsx lazy-loads (tree path) and its owner (scripts/module-map.json). '
    + '`start`: STUDIO_START_SECTION. `categories`: STUDIO_CATEGORIES of studioGates.ts.';

describe('Studio sections inventory', () => {
    it('matches the golden', () => {
        const sections = STUDIO_SECTIONS.map((s, i) => sectionRow(s, i));
        expect(sections.length).toBeGreaterThanOrEqual(14);
        expect(sections.every((s) => s.component)).toBe(true);
        checkGolden(import.meta.url, COMMENT, {
            sections,
            start: sectionRow(STUDIO_START_SECTION, -1),
            categories: STUDIO_CATEGORIES.map((c, position) => ({ position, ...c })),
        });
    });
});
