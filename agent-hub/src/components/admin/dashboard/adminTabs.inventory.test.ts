/**
 * GUI inventory: the admin dashboard (/app/admin/<tab>/<section>), recorded from
 * the running tables of adminTabs.ts and adminTabRows.ts. Per tab: its place
 * (ADMIN_TABS order is the fallback-tab order), rail group, i18n label key, icon,
 * every gate it carries (permissions, tier, capability, cloud / self-hosted,
 * platform admin, scope; a `railGate` is run, test/guiInventory/gates.ts), the
 * panel AdminTabContent.tsx renders for it (read with the TypeScript compiler
 * API) and that panel's owner; per tab its rail rows, each with its gate run.
 * The Organisation tab's rows are organisation sections: see
 * organisation/orgSections.inventory.test.ts.
 *
 * Regenerate: UPDATE_GOLDEN=1 npx vitest run src/components/admin/dashboard/adminTabs.inventory.test.ts
 */
import { describe, expect, it } from 'vitest';
import { checkGolden } from '@/test/guiInventory/golden';
import { probeGate } from '@/test/guiInventory/gates';
import { iconName } from '@/test/guiInventory/icons';
import { ownersOf } from '@/test/guiInventory/ownership';
import { loadSource, objectMapRefs } from '@/test/guiInventory/sourceAst';
import type { AdminRailRowDef } from './adminRailRowDef';
import { ADMIN_RAIL_ORDER, ADMIN_TAB_GROUPS, ADMIN_TABS } from './adminTabs';

const ICON_FILES = ['src/components/admin/dashboard/adminTabs.ts', 'src/components/admin/dashboard/adminTabRows.ts', 'src/components/admin/organisation/orgSections.ts'];
const RAIL_CTX = { calls: ['hasFeature', 'hasTier'], lists: ['agentSections'] } as const;
const panels = new Map(objectMapRefs(loadSource('src/components/admin/dashboard/AdminTabContent.tsx'), 'PANELS').map((p) => [p.key, p.components]));

function railRow(r: AdminRailRowDef, position: number) {
    return {
        position, section: r.section, labelKey: r.labelKey, labelFallback: r.labelFallback, descriptionKey: r.descriptionKey,
        icon: iconName(r.icon, ICON_FILES), group: r.group, block: r.block, kind: r.kind,
        gate: r.gate ? probeGate(r.gate as (ctx: never) => unknown, RAIL_CTX) : [], serverWide: r.serverWide, escapesChrome: r.escapesChrome,
    };
}

const COMMENT = 'Generated by components/admin/dashboard/adminTabs.inventory.test.ts (UPDATE_GOLDEN=1). `tabs`: ADMIN_TABS in '
    + 'order with every gate field, the railGate as run, the panel AdminTabContent.tsx PANELS renders (files, the first is '
    + 'the panel) and its owner. `railRows`: each tab\'s rows with their gates as run. `groups`: ADMIN_TAB_GROUPS. '
    + '`railOrder`: ADMIN_RAIL_ORDER.';

describe('admin dashboard inventory', () => {
    it('matches the golden', () => {
        const tabs = ADMIN_TABS.map((t, position) => {
            const files = (panels.get(t.id) ?? []).map((c) => c.file).filter((f): f is string => !!f);
            return {
                position, id: t.id, group: t.group, labelKey: t.labelKey, labelFallback: t.labelFallback, descriptionKey: t.descriptionKey,
                icon: iconName(t.icon, ICON_FILES), perm: t.perm, scope: t.scope, superAdminOnly: t.superAdminOnly, minTier: t.minTier,
                capability: t.capability, cloudOnly: t.cloudOnly, selfHostedOnly: t.selfHostedOnly, escapesChrome: t.escapesChrome,
                railGate: t.railGate ? probeGate(t.railGate as (ctx: never) => unknown, RAIL_CTX) : undefined,
                components: files, owner: ownersOf(files.slice(0, 1)),
            };
        });
        const railRows = Object.fromEntries(ADMIN_TABS.filter((t) => t.railRows?.length && t.id !== 'organisation')
            .map((t) => [t.id, (t.railRows ?? []).map(railRow)]));
        expect(tabs.length).toBeGreaterThan(15);
        checkGolden(import.meta.url, COMMENT, { tabs, railRows, groups: ADMIN_TAB_GROUPS, railOrder: ADMIN_RAIL_ORDER });
    });
});
