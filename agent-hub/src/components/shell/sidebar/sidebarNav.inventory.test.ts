/**
 * GUI inventory: the sidebar's rows (sidebarNav.tsx buildCoreNav and
 * buildSecondaryNav), built by the running code with every option that adds a
 * row switched on, and the Studio flyout as studioNavSections() resolves it
 * for someone every gate lets in. Per row: its place, key, i18n label key,
 * icon, the options that gate it (each option flipped in turn,
 * test/guiInventory/gates.ts probeOptions), where its click navigates, and the
 * screen of that destination with its owner (a Studio row: the section's
 * screen; a page: test/guiInventory/pages.ts).
 *
 * mobile/src/features/shell/model/sidebarNav.lockstep.test.ts reads the golden.
 * Regenerate: UPDATE_GOLDEN=1 npx vitest run src/components/shell/sidebar/sidebarNav.inventory.test.ts
 */
import { describe, expect, it } from 'vitest';
import { STUDIO_APPS } from '@/components/admin/Studio/studioApps';
import { studioNavSections } from '@/components/admin/Studio/studioNav';
import { checkGolden } from '@/test/guiInventory/golden';
import { keyT, probeOptions } from '@/test/guiInventory/gates';
import { iconName } from '@/test/guiInventory/icons';
import { ownersOf } from '@/test/guiInventory/ownership';
import { pageScreen } from '@/test/guiInventory/pages';
import { loadSource } from '@/test/guiInventory/sourceAst';
import { buildCoreNav, buildSecondaryNav, type CoreNavOptions, type NavItem, type SecondaryNavOptions } from './sidebarNav';

const NAV_FILE = 'src/components/shell/sidebar/sidebarNav.tsx';
const registry = loadSource('src/components/admin/Studio/studioRegistry.tsx');
const yes = () => true;
const everyone = { permissions: ['all'], isAdmin: true, role: 'admin' };
const studioSections = studioNavSections(STUDIO_APPS, {
    user: everyone, hasLicenseFeature: yes, hasPermission: yes, canUse: yes, can: yes, lockReason: () => null,
} as never);

let navigatedTo: string | null = null;
const onNavigate = (target: string) => { navigatedTo = target; };
const noop = () => undefined;

const CORE: CoreNavOptions = {
    t: keyT, onDirectChat: noop, newChatActive: false, onNavigate, currentPage: 'agents', studioSection: null,
    activeCoworkCount: 0, showApprovals: true, pendingApprovalCount: 0, onOpenSearch: noop, isMobile: false,
};
const SECONDARY: SecondaryNavOptions = {
    t: keyT, locale: 'en', studioCounts: null, onNavigate, currentPage: 'agents', studioSection: null,
    onOpenMarketplace: noop, showMarketplace: false, user: everyone as never,
    studioSections: studioSections as never, publishedApps: [], publishedForms: [],
};

/** Where a row's click goes: the page it navigates to, or null for an action (a dialog, a callback). */
function destination(row: NavItem): string | null {
    navigatedTo = null;
    row.onClick?.();
    return navigatedTo;
}

/** The screen a destination opens: a Studio section's, or a page's. */
function screenFile(target: string | null): string | null {
    if (!target) return null;
    const [page, segment] = target.split('/');
    if (page === 'studio' && segment) {
        const section = STUDIO_APPS.find((s) => s.urlSegment === segment);
        return section ? registry.lazies.get(section.id) ?? null : null;
    }
    return pageScreen(page)?.file ?? null;
}

function rowOf(row: NavItem, position: number, gates: Record<string, string[]>) {
    const to = destination(row);
    const component = screenFile(to);
    return {
        position,
        key: row.key,
        labelKey: row.label,
        descKey: row.desc ?? undefined,
        icon: iconName(row.icon, [NAV_FILE, 'src/components/admin/Studio/studioSections.ts']),
        gate: gates[row.key] ?? [],
        navigatesTo: to,
        component,
        // A row without a screen (New Chat, Search, the store) belongs to the file that declares it.
        owner: ownersOf([component ?? NAV_FILE]),
    };
}

const COMMENT = 'Generated by components/shell/sidebar/sidebarNav.inventory.test.ts (UPDATE_GOLDEN=1). `core`: buildCoreNav, '
    + '`secondary`: buildSecondaryNav, each row with the options that gate it, where its click navigates and the screen there '
    + '(file, owner; a row without one: the owner of sidebarNav.tsx);`flyouts`: the children of each flyout row (the Studio one for someone every gate lets in, no published '
    + 'apps or forms).';

describe('sidebar nav inventory', () => {
    it('matches the golden', () => {
        const coreGates = probeOptions(buildCoreNav, CORE, (r) => r.key);
        const secondaryGates = probeOptions(buildSecondaryNav, SECONDARY, (r) => r.key);
        const core = buildCoreNav(CORE).map((r, i) => rowOf(r, i, coreGates));
        const secondaryRows = buildSecondaryNav(SECONDARY);
        const secondary = secondaryRows.map((r, i) => rowOf(r, i, secondaryGates));
        const flyouts = Object.fromEntries(secondaryRows.filter((r) => r.flyout).map((r) => [r.key, r.flyout?.groups
            ? r.flyout.groups.flatMap((g) => g.children.map((c, i) => ({ group: g.key, groupLabelKey: g.label, ...rowOf(c, i, {}) })))
            : (r.flyout?.children ?? []).map((c, i) => rowOf(c, i, {}))]));
        expect(core.length).toBeGreaterThanOrEqual(4);
        expect(secondary.length).toBe(4);
        checkGolden(import.meta.url, COMMENT, { core, secondary, flyouts });
    });
});
