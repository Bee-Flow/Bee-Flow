/**
 * GUI inventory: the chat composer's menus. `toolsMenu`: the rows of the "+"
 * menu (composerTools.ts buildComposerTools), built by the running code with
 * every option that adds a row switched on; per row its place, id, group, kind,
 * i18n label key, icon and the options that gate it (each flipped in turn,
 * test/guiInventory/gates.ts probeOptions). `pickers`: the components
 * ComposerPills.tsx mounts beside and inside that menu (the pickers a panel row
 * hands off to and the pills), in source order, read with the TypeScript
 * compiler API, each with its file and owner. `apps`: the apps picker's fixed
 * catalogue (components/apps/appCatalog.tsx APP_DEFS) with the account each
 * needs.
 *
 * Regenerate: UPDATE_GOLDEN=1 npx vitest run src/components/chat/InputArea/composerTools.inventory.test.ts
 */
import { describe, expect, it } from 'vitest';
import { APP_DEFS } from '@/components/apps/appCatalog';
import { checkGolden } from '@/test/guiInventory/golden';
import { iconName } from '@/test/guiInventory/icons';
import { keyT, probeOptions } from '@/test/guiInventory/gates';
import { ownerOf, ownersOf } from '@/test/guiInventory/ownership';
import { componentRefs, loadSource } from '@/test/guiInventory/sourceAst';
import { buildComposerTools, type ComposerTool, type ComposerToolsProps } from './composerTools';

const TOOLS_FILE = 'src/components/chat/InputArea/composerTools.ts';
const noop = () => undefined;
const ALL_ON: ComposerToolsProps = {
    t: keyT as ComposerToolsProps['t'], onAttachClick: noop, incognito: false,
    canCreateMedia: true, mediaMenuOpen: false, setMediaMenuOpen: noop,
    canFillTemplate: true, templatesOpen: false, setTemplatesOpen: noop,
    canPickApps: true, appsOpen: false, setAppsOpen: noop,
    canWebSearch: true, webSearchEnabled: false, webSearchBlocked: false, webSearchUnavailable: null, setWebSearchEnabled: noop,
    simpleMode: false, showTierSlider: false, memoryMode: 'on', changeMemoryMode: noop, memoryLock: null,
    voiceReady: true, voiceMode: false, setVoiceMode: noop,
};

const rows = (o: ComposerToolsProps) => buildComposerTools(o).filter((r): r is ComposerTool => !!r);

const COMMENT = 'Generated by components/chat/InputArea/composerTools.inventory.test.ts (UPDATE_GOLDEN=1). `toolsMenu`: '
    + 'buildComposerTools with every row on, each row with the options that gate it. `pickers`: the components '
    + 'ComposerPills.tsx mounts, in source order (file, owner). `apps`: APP_DEFS with the account each needs.';

describe('composer inventory', () => {
    it('matches the golden', () => {
        const gates = probeOptions(rows, ALL_ON, (r) => r.id);
        const toolsMenu = rows(ALL_ON).map((r, position) => ({
            position, id: r.id, group: r.group, kind: r.kind, labelKey: r.label, icon: iconName(r.icon, [TOOLS_FILE]),
            beta: r.beta, gate: gates[r.id] ?? [], owner: ownerOf(TOOLS_FILE),
        }));
        const pills = loadSource('src/components/chat/InputArea/ComposerPills.tsx');
        const pickers = componentRefs(pills, pills.sf).map((c, position) => ({ position, name: c.name, component: c.file, owner: ownersOf([c.file]) }));
        const apps = APP_DEFS.map((a, position) => ({
            position, id: a.id, label: a.label,
            needs: Object.entries(a).filter(([k, v]) => k.startsWith('requires') && v === true).map(([k]) => k),
        }));
        expect(toolsMenu.length).toBeGreaterThanOrEqual(6);
        checkGolden(import.meta.url, COMMENT, { toolsMenu, pickers, apps });
    });
});
