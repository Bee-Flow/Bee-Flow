/**
 * GUI inventory: the app's addresses (appRoutes.ts APP_ROUTES, PAGE_ROUTES and
 * MOBILE_ALLOWED_PAGES), recorded from the running module. Per route row: its
 * place (first match wins), pattern, page, access gate and redirect; per page:
 * the screen it renders (AuthedApp.tsx and AgentHub/HubMainContent.tsx, read with
 * the TypeScript compiler API, test/guiInventory/pages.ts), that screen's file
 * and its owner in the ownership map, and whether a phone may open it.
 *
 * Regenerate: UPDATE_GOLDEN=1 npx vitest run src/authedApp/appRoutes.inventory.test.ts
 */
import { describe, expect, it } from 'vitest';
import { checkGolden } from '@/test/guiInventory/golden';
import { ownersOf } from '@/test/guiInventory/ownership';
import { pageScreen } from '@/test/guiInventory/pages';
import { APP_ROUTES, MOBILE_ALLOWED_PAGES, PAGE_ROUTES } from './appRoutes';

const COMMENT = 'Generated by authedApp/appRoutes.inventory.test.ts (UPDATE_GOLDEN=1). `routes`: APP_ROUTES in match order. '
    + '`pages`: PAGE_ROUTES with the screen each page key renders (AuthedApp.tsx / HubMainContent.tsx branches; no branch: '
    + 'AgentHub), its file, its owner, and `mobile` (MOBILE_ALLOWED_PAGES).';

function screenOf(page: string) {
    const screen = pageScreen(page);
    return { screen: screen?.name ?? null, component: screen?.file ?? null, owner: ownersOf([screen?.file]) };
}

describe('app routes inventory', () => {
    it('matches the golden', () => {
        const routes = APP_ROUTES.map((r, position) => ({ position, pattern: r.pattern, page: r.page, access: r.access, redirect: r.redirect }));
        const pageKeys = [...new Set([...Object.keys(PAGE_ROUTES), ...APP_ROUTES.map((r) => r.page), ...MOBILE_ALLOWED_PAGES])];
        const pages = pageKeys.map((page, position) => ({
            position,
            page,
            path: PAGE_ROUTES[page],
            mobile: MOBILE_ALLOWED_PAGES.has(page),
            ...screenOf(page),
        }));
        expect(routes.length).toBeGreaterThan(40);
        checkGolden(import.meta.url, COMMENT, { routes, pages, mobileAllowed: [...MOBILE_ALLOWED_PAGES] });
    });
});
