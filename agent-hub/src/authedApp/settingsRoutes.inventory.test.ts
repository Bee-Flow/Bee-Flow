/**
 * GUI inventory: the Settings screen (/app/settings/*), recorded from the
 * running tables of settingsRoutes.ts and pages/settings/settingsNavItems.tsx.
 * Per top-level tab: its place, address, i18n label key, icon, whether a phone
 * gets it, and the section renderSettingsContent.tsx draws for it (its branch,
 * read with the TypeScript compiler API) with that section's owner. Then the
 * account and organisation sub-tabs with their addresses, the dashboard page
 * each organisation sub-tab moved to, and the phone's organisation list
 * (pages/AdvancedSettings.tsx BASE_ORG_SUB_ITEMS and AZURE_SUB_ITEM, which the
 * module does not export: read as data from its syntax tree).
 *
 * mobile/src/features/org/model/sections.lockstep.test.ts,
 * mobile/src/features/notifications/model/routeOrg.lockstep.test.ts and
 * mobile/src/shared/markdown/links.lockstep.test.ts read the golden.
 * Regenerate: UPDATE_GOLDEN=1 npx vitest run src/authedApp/settingsRoutes.inventory.test.ts
 */
import { describe, expect, it } from 'vitest';
import { SECTIONS as ORG_INFO_SECTIONS } from '@/components/admin/org/orgInfo/orgInfoShared';
import {
    MOBILE_EXTRA_TABS, MOBILE_VISIBLE_TOP_TABS, NAV_ITEMS, SETTINGS_DESKTOP_ONLY_TABS, SETTINGS_RESOURCE_TABS,
} from '@/pages/settings/settingsNavItems';
import { checkGolden } from '@/test/guiInventory/golden';
import { iconName } from '@/test/guiInventory/icons';
import { ownersOf } from '@/test/guiInventory/ownership';
import { literalBranches, literalRows, loadSource } from '@/test/guiInventory/sourceAst';
import {
    ORG_SETTINGS_ADMIN_TARGETS, ORG_USERS_TAB_TO_SECURITY, SETTINGS_ACCOUNT_ID_TO_URL, SETTINGS_GROUP_SEGMENTS,
    SETTINGS_LEGACY_SEGMENT_ALIASES, SETTINGS_ORG_ADMIN_TARGETS, SETTINGS_ORG_ID_TO_URL, SETTINGS_TOP_LEVEL_TAB_IDS,
    USAGE_REPORT_TO_MONITORING, settingsPathForTab,
} from './settingsRoutes';

const NAV_FILE = 'src/pages/settings/settingsNavItems.tsx';
const content = literalBranches(loadSource('src/pages/settings/shell/renderSettingsContent.tsx'), ['activeTab']);

/**
 * What a tab draws: the components of its own branch of renderSettingsContent
 * (a wrapper such as RequireTier included), or none: an organisation tab
 * without a branch is drawn by the default one (OrganisationSection), and on a
 * desktop opens its `adminTarget` instead.
 */
function section(id: string) {
    const files = (content.get(id) ?? []).map((r) => r.file).filter((f): f is string => !!f);
    return { components: files, owner: ownersOf(files) };
}

const COMMENT = 'Generated by authedApp/settingsRoutes.inventory.test.ts (UPDATE_GOLDEN=1). `topLevel`: '
    + 'SETTINGS_TOP_LEVEL_TAB_IDS with the nav row (settingsNavItems NAV_ITEMS), the phone rules and the section '
    + 'renderSettingsContent.tsx draws (file, owner). `account` / `organisation`: the sub-tabs with their address (and '
    + 'the dashboard page an organisation one moved to). `phoneOrgList`: the organisation rows AdvancedSettings.tsx lists '
    + 'for a phone, `...ORG_SECTIONS` expanded from orgInfoShared SECTIONS.';

function phoneOrgList() {
    const settings = loadSource('src/pages/AdvancedSettings.tsx');
    const rows = [...literalRows(settings, 'BASE_ORG_SUB_ITEMS'), ...literalRows(settings, 'AZURE_SUB_ITEM')];
    return rows.flatMap((r) => (r.spread === 'ORG_SECTIONS'
        ? ORG_INFO_SECTIONS.map((s) => ({ id: s.id, labelKey: s.labelKey, icon: iconName(s.icon, ['src/components/admin/org/orgInfo/orgInfoShared.tsx']) }))
        : [{ id: r.id, labelKey: r.labelKey, icon: r.icon }]))
        .map((r, position) => ({ position, ...r }));
}

describe('settings inventory', () => {
    it('matches the golden', () => {
        const topLevel = SETTINGS_TOP_LEVEL_TAB_IDS.map((id, position) => {
            const nav = NAV_ITEMS.find((n) => n.id === id);
            return {
                position, id, path: settingsPathForTab(id), labelKey: nav?.labelKey, icon: iconName(nav?.icon, [NAV_FILE]),
                phone: MOBILE_VISIBLE_TOP_TABS.includes(id), desktopOnly: SETTINGS_DESKTOP_ONLY_TABS.includes(id),
                resource: SETTINGS_RESOURCE_TABS.includes(id), ...section(id),
            };
        });
        const account = Object.entries(SETTINGS_ACCOUNT_ID_TO_URL)
            .map(([id, segment], position) => ({ position, id, segment, path: settingsPathForTab(id), ...section(id) }));
        const organisation = Object.entries(SETTINGS_ORG_ID_TO_URL).map(([id, segment], position) => ({
            position, id, segment, path: settingsPathForTab(id), adminTarget: SETTINGS_ORG_ADMIN_TARGETS[id],
            phone: MOBILE_EXTRA_TABS.includes(id), ...section(id),
        }));
        expect(topLevel.length).toBeGreaterThanOrEqual(8);
        expect(organisation.length).toBeGreaterThan(10);
        checkGolden(import.meta.url, COMMENT, {
            topLevel,
            groupSegments: SETTINGS_GROUP_SEGMENTS,
            legacyAliases: SETTINGS_LEGACY_SEGMENT_ALIASES,
            desktopOnly: SETTINGS_DESKTOP_ONLY_TABS,
            account,
            organisation,
            phoneOrgList: phoneOrgList(),
            usageReports: USAGE_REPORT_TO_MONITORING,
            orgUsersTabs: ORG_USERS_TAB_TO_SECURITY,
            orgSettingsPage: ORG_SETTINGS_ADMIN_TARGETS,
        });
    });
});
