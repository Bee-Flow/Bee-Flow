/**
 * A gate that only ever passes is indistinguishable from no gate.
 *
 * check-editor-bundles.mjs has one job: go RED when an editor source changed
 * and the generated server bundle was not rebuilt. The sandboxes below are
 * small stand-ins for server/ and agent-hub/ with bundles stamped by the real
 * bannerFor/hashInputs.
 */

import test from 'node:test';
import assert from 'node:assert';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { check } from './check-editor-bundles.mjs';
import { build } from './build-editor-bundles.mjs';
import { BUNDLES, bannerFor, hashInputs, recordedHash, recordedInputs } from './lib/editor-bundles.mjs';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** A fake server/ whose two bundles are stamped from fake agent-hub sources. */
function sandbox(t) {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'editorbundles-'));
    t.after(() => fs.rmSync(root, { recursive: true, force: true }));
    const server = path.join(root, 'server');
    fs.mkdirSync(path.join(server, 'core/markdown'), { recursive: true });
    for (const b of Object.values(BUNDLES)) {
        const abs = path.join(server, b.entry);
        fs.mkdirSync(path.dirname(abs), { recursive: true });
        fs.writeFileSync(abs, `export const entry = 1;\n`);
    }
    const helper = '../agent-hub/src/editor/model/helper.js';
    fs.mkdirSync(path.join(server, path.dirname(helper)), { recursive: true });
    fs.writeFileSync(path.join(server, helper), 'export const h = 1;\n');
    for (const [name, b] of Object.entries(BUNDLES)) {
        const inputs = [b.entry, helper];
        fs.writeFileSync(path.join(server, b.out), `${bannerFor(name, hashInputs(server, inputs), inputs)}\n"use strict";\n`);
    }
    return { server, helper };
}

test('fresh bundles pass', (t) => {
    const { server } = sandbox(t);
    const lines = [];
    assert.deepStrictEqual(check(server, (l) => lines.push(l)), []);
    assert.strictEqual(lines.length, 2);
});

test('a changed input, even one with no code in the bundle, is stale', (t) => {
    const { server, helper } = sandbox(t);
    fs.appendFileSync(path.join(server, helper), 'export const added = 2;\n');
    const problems = check(server, () => {});
    assert.strictEqual(problems.length, 2);
    assert.match(problems[0], /stale/);
    assert.match(problems[0], /npm run build:editor-md/);
    assert.match(problems[1], /npm run build:editor-collab/);
});

test('CRLF checkouts hash like LF ones', (t) => {
    const { server, helper } = sandbox(t);
    const f = path.join(server, helper);
    fs.writeFileSync(f, fs.readFileSync(f, 'utf8').replace(/\n/g, '\r\n'));
    assert.deepStrictEqual(check(server, () => {}), []);
});

test('a bundle without the hash line fails', (t) => {
    const { server } = sandbox(t);
    fs.writeFileSync(path.join(server, BUNDLES.md.out), '"use strict";\n');
    const problems = check(server, () => {});
    assert.strictEqual(problems.length, 1);
    assert.match(problems[0], /no "inputs-sha256:" line/);
});

test('a missing bundle and a missing input fail instead of skipping', (t) => {
    const { server, helper } = sandbox(t);
    fs.rmSync(path.join(server, BUNDLES.md.out));
    fs.rmSync(path.join(server, helper));
    const problems = check(server, () => {});
    assert.match(problems[0], /missing/);
    assert.match(problems[1], /cannot read an input/);
});

test('a banner that does not list its entry fails', (t) => {
    const { server } = sandbox(t);
    const f = path.join(server, BUNDLES.collab.out);
    fs.writeFileSync(f, fs.readFileSync(f, 'utf8').replace(BUNDLES.collab.entry, '../agent-hub/src/other.ts'));
    assert.match(check(server, () => {})[0], /does not list its entry/);
});

test('the banner round-trips and keeps the flags the npm script had', () => {
    const banner = bannerFor('collab', 'a'.repeat(64), ['b.js', 'a.js', 'a.js']);
    assert.match(banner.split('\n')[0], /^\/\* GENERATED by 'cd server && npm run build:editor-collab' from agent-hub\/src\/editor\/collab\/serverEntry\.ts\. Do not edit\. \*\/ \/\* eslint-disable \*\/ \/\* jscpd:ignore-start \*\/$/);
    assert.strictEqual(recordedHash(`${banner}\ncode`), 'a'.repeat(64));
    assert.deepStrictEqual(recordedInputs(`${banner}\ncode`), ['a.js', 'b.js']);
});

test('the committed bundles are fresh', () => {
    assert.deepStrictEqual(check(path.join(REPO, 'server'), () => {}), []);
});

// The build itself, with the esbuild the server locks. Skipped where the
// server has no install (the check above needs none).
let esbuild = null;
try {
    esbuild = createRequire(path.join(REPO, 'server/package.json'))('esbuild');
} catch {
    /* not installed */
}

test('building stamps a banner the check accepts, tree-shaken inputs included', { skip: !esbuild && 'esbuild is not installed' }, async (t) => {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'editorbuild-'));
    t.after(() => fs.rmSync(root, { recursive: true, force: true }));
    const server = path.join(root, 'server');
    fs.mkdirSync(path.join(server, 'core/markdown'), { recursive: true });
    fs.mkdirSync(path.join(root, 'agent-hub/src/editor/serialization'), { recursive: true });
    fs.mkdirSync(path.join(root, 'agent-hub/src/editor/collab'), { recursive: true });
    const dir = path.join(root, 'agent-hub/src/editor');
    // `unused` is imported but contributes no code: it must still count as an input.
    fs.writeFileSync(path.join(dir, 'unused.js'), 'export const unused = 1;\n');
    fs.writeFileSync(path.join(dir, 'serialization/index.ts'), "import { unused } from '../unused.js';\nexport const a = 1;\nvoid unused;\n");
    fs.writeFileSync(path.join(dir, 'collab/serverEntry.ts'), "export const b: number = 2;\n");
    const r = await build('md', { esbuild, baseDir: server });
    await build('collab', { esbuild, baseDir: server });
    assert.deepStrictEqual(check(server, () => {}), []);
    const text = fs.readFileSync(path.join(server, BUNDLES.md.out), 'utf8');
    assert.ok(recordedInputs(text).includes('../agent-hub/src/editor/unused.js'));
    assert.strictEqual(recordedHash(text), r.hash);
    fs.appendFileSync(path.join(dir, 'unused.js'), '// edited\n');
    assert.match(check(server, () => {})[0], /stale/);
});
