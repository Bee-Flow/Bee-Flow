#!/usr/bin/env node
/**
 * Generate server/types/rows.d.ts: one TypeScript interface per table, read from the
 * `CREATE TABLE` / `ALTER TABLE ... ADD COLUMN` statements in the server sources (the stores
 * create their own schema; there is no migration folder with the whole shape).
 *
 * The interfaces describe what the `pg` driver hands back WITHOUT custom type parsers:
 * bigint and numeric arrive as strings, timestamp/date as Date, json/jsonb as parsed values.
 * A column is `| null` unless it is NOT NULL or part of the primary key. A table whose name is
 * built with `${...}` is skipped, and so is a column definition that is.
 * Use them from JSDoc: `@param {DbRow.Users} row`.
 *
 * Usage:
 *   node scripts/gen-row-types.mjs            write server/types/rows.d.ts
 *   node scripts/gen-row-types.mjs --check    fail when the file is stale (lint:row-types)
 */

import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { isEntryPoint } from './entry-point.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SERVER = path.join(ROOT, 'server');
const OUT = path.join(SERVER, 'types', 'rows.d.ts');
const SKIP_DIR = new Set(['node_modules', 'coverage', 'types', 'scratch']);
const SKIP_FILE = /\.(test|testkit|testutil|fixture|golden)\.[cm]?js$|\.testkit\.|testSchema\.js$/;
export const HEADER = '// GENERATED by scripts/gen-row-types.mjs from the CREATE TABLE statements in server/. Do not edit.\n// Run `npm run gen:row-types` after a schema change. Types are what the pg driver returns by default.\n';

/** @param {string} dir @returns {string[]} server source files that can hold schema statements */
export function sourceFiles(dir = SERVER, prefix = '') {
    const out = [];
    for (const e of readdirSync(dir, { withFileTypes: true })) {
        const rel = prefix ? `${prefix}/${e.name}` : e.name;
        if (e.isDirectory()) {
            if (!SKIP_DIR.has(e.name)) out.push(...sourceFiles(path.join(dir, e.name), rel));
        } else if (/\.[cm]?js$/.test(e.name) && !SKIP_FILE.test(e.name)) out.push(rel);
    }
    return out.sort();
}

/** The text between the parenthesis that opens at `open` and its partner, or null. */
function balanced(text, open) {
    let depth = 0;
    let quote = null;
    for (let i = open; i < text.length; i++) {
        const c = text[i];
        if (quote) { if (c === quote) quote = null; continue; }
        if (c === "'") quote = c;
        else if (c === '(') depth++;
        else if (c === ')' && --depth === 0) return text.slice(open + 1, i);
    }
    return null;
}

/** Split on commas that are not inside parentheses or quotes. */
function splitTop(body) {
    const parts = [];
    let depth = 0, quote = null, last = 0;
    for (let i = 0; i < body.length; i++) {
        const c = body[i];
        if (quote) { if (c === quote) quote = null; continue; }
        if (c === "'") quote = c;
        else if (c === '(') depth++;
        else if (c === ')') depth--;
        else if (c === ',' && depth === 0) { parts.push(body.slice(last, i)); last = i + 1; }
    }
    parts.push(body.slice(last));
    return parts.map((p) => p.replace(/--[^\n]*/g, '').trim()).filter(Boolean);
}

const CONSTRAINT = /^(PRIMARY\s+KEY|UNIQUE|FOREIGN\s+KEY|CONSTRAINT|CHECK|EXCLUDE|LIKE)\b/i;

/** SQL type text -> the TypeScript type the pg driver produces. */
export function tsType(sql) {
    let t = sql.trim().toLowerCase().replace(/\s+/g, ' ');
    const array = /\[\s*\d*\s*\]\s*$/.test(t) || /^array\b/.test(t);
    t = t.replace(/\[\s*\d*\s*\]/g, '').replace(/\(.*?\)/g, '').trim();
    const base = (() => {
        if (/^(text|varchar|character varying|char|character|bpchar|citext|uuid|name|inet|cidr|macaddr|interval|time|timetz|time without time zone|time with time zone|tsvector|money|bigint|int8|bigserial|serial8|numeric|decimal)\b/.test(t)) return 'string';
        if (/^(int|integer|int4|int2|smallint|serial|serial4|smallserial|real|float4|float8|float|double precision|oid)\b/.test(t)) return 'number';
        if (/^(boolean|bool)\b/.test(t)) return 'boolean';
        if (/^(timestamp|timestamptz|date)\b/.test(t)) return 'Date';
        if (/^(json|jsonb)\b/.test(t)) return 'Json';
        if (/^bytea\b/.test(t)) return 'Buffer';
        return 'unknown';
    })();
    return array ? `${base}[]` : base;
}

/** Cut the type off a column definition at the first constraint keyword. */
function splitColumn(def) {
    const m = /^("?)([A-Za-z_][A-Za-z0-9_]*)\1\s+(.*)$/s.exec(def);
    if (!m) return null;
    const rest = m[3];
    const stop = /\b(NOT\s+NULL|NULL|DEFAULT|PRIMARY\s+KEY|REFERENCES|UNIQUE|CHECK|CONSTRAINT|GENERATED|COLLATE)\b/i.exec(rest);
    const type = (stop ? rest.slice(0, stop.index) : rest).trim();
    const flags = stop ? rest.slice(stop.index) : '';
    return { name: m[2], type, notNull: /\bNOT\s+NULL\b/i.test(flags) || /\bPRIMARY\s+KEY\b/i.test(flags) || /\bGENERATED\b.*\bIDENTITY\b/i.test(flags) };
}

/** @returns {Map<string, Map<string, { ts: string, notNull: boolean }>>} table -> column -> type */
export function parseSchema(texts) {
    const tables = new Map();
    const addColumn = (table, c) => {
        if (!tables.has(table)) tables.set(table, new Map());
        const cols = tables.get(table);
        const prev = cols.get(c.name);
        // Seen twice (a CREATE and a later ALTER, or two stores): keep the first type, null if either allows it.
        cols.set(c.name, prev ? { ts: prev.ts, notNull: prev.notNull && c.notNull } : { ts: tsType(c.type), notNull: c.notNull });
    };
    for (const text of texts) {
        const create = /CREATE\s+(?:UNLOGGED\s+)?TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?(?:public\.)?("?)([a-z_][a-z0-9_]*)\1\s*\(/gi;
        let m;
        while ((m = create.exec(text))) {
            const body = balanced(text, m.index + m[0].length - 1);
            if (body === null) continue;
            const pk = new Set();
            const cols = [];
            for (const def of splitTop(body)) {
                if (def.includes('${')) continue;
                const pkm = /^PRIMARY\s+KEY\s*\(([^)]*)\)/i.exec(def);
                if (pkm) { for (const n of pkm[1].split(',')) pk.add(n.trim().replace(/"/g, '')); continue; }
                if (CONSTRAINT.test(def)) continue;
                const c = splitColumn(def);
                if (c) cols.push(c);
            }
            for (const c of cols) addColumn(m[2], { ...c, notNull: c.notNull || pk.has(c.name) });
        }
        const alter = /ALTER\s+TABLE\s+(?:IF\s+EXISTS\s+)?(?:ONLY\s+)?(?:public\.)?("?)([a-z_][a-z0-9_]*)\1\s+((?:ADD\s+COLUMN[^;`]*?)(?=;|`|$))/gi;
        while ((m = alter.exec(text))) {
            for (const part of splitTop(m[3])) {
                const a = /^ADD\s+COLUMN\s+(?:IF\s+NOT\s+EXISTS\s+)?(.*)$/is.exec(part);
                if (!a || a[1].includes('${')) continue;
                const c = splitColumn(a[1]);
                if (c) addColumn(m[2], c);
            }
        }
    }
    return tables;
}

const pascal = (s) => s.split('_').filter(Boolean).map((p) => p[0].toUpperCase() + p.slice(1)).join('');

/** The text of rows.d.ts for a parsed schema. */
export function render(tables) {
    const lines = [HEADER, 'type Json = any;', '', 'declare namespace DbRow {'];
    for (const table of [...tables.keys()].sort()) {
        lines.push(`    /** Row of \`${table}\`. */`, `    interface ${pascal(table)} {`);
        for (const [name, c] of [...tables.get(table)].sort((a, b) => a[0].localeCompare(b[0]))) {
            lines.push(`        ${name}: ${c.ts}${c.notNull ? '' : ' | null'};`);
        }
        lines.push('    }');
    }
    lines.push('}', '');
    return lines.join('\n');
}

export function generate(serverDir = SERVER) {
    const texts = sourceFiles(serverDir).map((f) => readFileSync(path.join(serverDir, f), 'utf8')).filter((t) => /CREATE\s+(UNLOGGED\s+)?TABLE|ADD\s+COLUMN/i.test(t));
    return render(parseSchema(texts));
}

if (isEntryPoint(import.meta.url)) {
    const next = generate();
    if (process.argv.includes('--check')) {
        const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
        if (current !== next) {
            console.error('row-types: server/types/rows.d.ts is stale. Fix: npm run gen:row-types');
            process.exit(1);
        }
        console.log('row-types: server/types/rows.d.ts is fresh');
    } else {
        writeFileSync(OUT, next);
        console.log(`row-types: wrote ${path.relative(ROOT, OUT)} (${next.split('\n').filter((l) => l.includes('interface ')).length} tables)`);
    }
}
