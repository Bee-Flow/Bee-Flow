#!/usr/bin/env node
/**
 * Generate the web's copies of the App Studio catalog from the server spec
 * (server/appStudio/componentSpecs.js), so nothing in agent-hub mirrors it by hand:
 *
 *   runtime/catalogSnapshot.generated.json  a trimmed slice: per type the palette data
 *                                            (label, category, container, isInput,
 *                                            defaultProps, defaultStyle and, when the
 *                                            spec has them, since / mobile / parts), the
 *                                            style knobs and their values, the events,
 *                                            the step kinds, the limits. Every top-level
 *                                            key is its own named import, so a bundle
 *                                            keeps only the keys it reads.
 *   inspector/typeEventLists.ts             the `events` of each type, as TypeScript
 *                                            (shared-mirror.manifest.json copies it to the
 *                                            phone, which cannot read agent-hub JSON).
 *   mobile/.../apps/model/catalogExtensions.generated.ts
 *                                            the component types added after the base
 *                                            (since >= 3) with the reason the phone leaves
 *                                            each to the browser (the spec's mobile.reason).
 *   demo/fixtures/appStudioCatalog.generated.json
 *                                            buildCatalog() as GET /api/studio-apps/catalog
 *                                            answers it, components narrowed to DEMO_TYPES
 *                                            (no comment key: the demo serves it as is;
 *                                            appStudioCatalog.ts says where it comes from).
 *
 * The spec is dependency-free plain data (the web and phone tests require it too), so
 * this runs without server/node_modules and --check belongs in lint:shared-mirror.
 *
 * The AI tool names are the exception: server/appStudio/builderTools/schemas.js loads
 * the document store. `--tools` writes chat/appToolNames.generated.json from it and needs
 * server/node_modules; server/appStudio/builderTools/toolNames.mirror.test.js is the gate.
 *
 * Usage:
 *   node scripts/gen-app-catalog.mjs            write the four files (npm run gen:shared runs this)
 *   node scripts/gen-app-catalog.mjs --check    exit 1 when one is stale; writes nothing
 *   node scripts/gen-app-catalog.mjs --tools    write the AI tool name list only
 */

import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { isEntryPoint } from './entry-point.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SPEC_FILE = 'server/appStudio/componentSpecs.js';
const TOOLS_FILE = 'server/appStudio/builderTools/schemas.js';
const STUDIO = 'agent-hub/src/components/admin/Studio/AppStudio';
export const OUT = {
    snapshot: `${STUDIO}/runtime/catalogSnapshot.generated.json`,
    typeEvents: `${STUDIO}/inspector/typeEventLists.ts`,
    demo: 'agent-hub/src/demo/fixtures/appStudioCatalog.generated.json',
    mobileExtensions: 'mobile/src/features/apps/model/catalogExtensions.generated.ts',
    tools: `${STUDIO}/chat/appToolNames.generated.json`,
};
const COMMENT = `GENERATED by scripts/gen-app-catalog.mjs from ${SPEC_FILE}: do not edit. Run \`npm run gen:shared\`.`;

/** The types the demo's catalog answer carries: the fixture app's own plus the likeliest drops. */
export const DEMO_TYPES = [
    'heading', 'text', 'filter_bar', 'kanban', 'record_detail', 'button', 'callout', 'stat',
    'table', 'data_grid', 'chart', 'list', 'card', 'form', 'input_text', 'input_select', 'ai_chat',
];

/** Fields copied onto a type's snapshot entry only when the spec carries them. */
const OPTIONAL_TYPE_FIELDS = ['since', 'mobile', 'parts'];

/**
 * The spec's per-prop defaults: exactly what canonicalize fills in (absent = null).
 * A prop marked `since` 3 or later is never filled in, so it is not here either.
 */
export function defaultPropsOf(spec) {
    const out = {};
    for (const [key, field] of Object.entries(spec.props || {})) {
        if (typeof field.since === 'number' && field.since >= 3) continue;
        out[key] = field.default === undefined ? null : field.default;
    }
    return out;
}

function typeEntry(spec) {
    const entry = { label: spec.label, category: spec.category };
    if (spec.container) entry.container = true;
    if (spec.isInput) entry.isInput = true;
    entry.defaultProps = defaultPropsOf(spec);
    entry.defaultStyle = spec.defaultStyle || {};
    for (const field of OPTIONAL_TYPE_FIELDS) if (spec[field] !== undefined) entry[field] = spec[field];
    return entry;
}

function enumFields(table) {
    const out = {};
    for (const [key, field] of Object.entries(table)) if (field.type === 'enum') out[key] = field.values;
    return out;
}

function defaultsOf(table) {
    return Object.fromEntries(Object.entries(table).map(([key, field]) => [key, field.default === undefined ? null : field.default]));
}

function stepEntry(kind, spec, clientKinds) {
    const entry = { client: clientKinds.has(kind), mutatesData: !!spec.mutatesData };
    if (spec.since !== undefined) entry.since = spec.since;
    return entry;
}

/** The trimmed slice of the catalog the web bundles. `specs` is the required spec module. */
export function buildSnapshot(specs) {
    const typeNames = Object.keys(specs.COMPONENT_SPECS);
    const clientKinds = new Set(specs.CLIENT_STEP_KINDS);
    const pick = (fn) => Object.fromEntries(typeNames.map((t) => [t, fn(specs.COMPONENT_SPECS[t])]));
    const typeEvents = {};
    for (const t of typeNames) {
        const events = specs.COMPONENT_SPECS[t].events;
        if (Array.isArray(events) && events.length) typeEvents[t] = events;
    }
    return {
        $comment: COMMENT,
        schemaVersion: specs.SCHEMA_VERSION_CURRENT,
        limits: specs.LIMITS,
        colorRoles: specs.COLOR_ROLES,
        styleKnobs: specs.STYLE_KNOBS,
        advancedWidthKnobs: specs.ADVANCED_WIDTH_KNOBS,
        advancedHeightKnobs: specs.ADVANCED_HEIGHT_KNOBS,
        responsiveVisibilityKnobs: specs.RESPONSIVE_VISIBILITY_KNOBS,
        extensionKnobGroups: specs.EXTENSION_STYLE_KNOB_GROUPS,
        themeEnums: enumFields(specs.THEME_SPEC),
        screenEnums: enumFields(specs.SCREEN_SPEC),
        screenDefaults: defaultsOf(specs.SCREEN_SPEC),
        toastTones: specs.TOAST_TONES,
        formulaScopeRoots: specs.FORMULA_SCOPE_ROOTS,
        inputTypes: specs.INPUT_TYPES,
        eventNames: specs.EVENT_NAMES,
        steps: Object.fromEntries(specs.STEP_KINDS.map((k) => [k, stepEntry(k, specs.STEP_SPECS[k] || {}, clientKinds)])),
        types: pick(typeEntry),
        typeStyleKnobs: pick((spec) => spec.styleKnobs || []),
        typeEvents,
    };
}

const IDENT = /^[A-Za-z_$][\w$]*$/;
const quote = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/** inspector/typeEventLists.ts: the snapshot's typeEvents as a TypeScript module. */
export function renderTypeEventLists(snapshot) {
    const lines = Object.entries(snapshot.typeEvents).map(([type, events]) =>
        `    ${IDENT.test(type) ? type : quote(type)}: [${events.map(quote).join(', ')}],`);
    return [
        `// GENERATED by scripts/gen-app-catalog.mjs from the \`events\` of each type in ${SPEC_FILE}:`,
        '// do not edit. Run `npm run gen:shared` (it also refreshes the phone\'s copy).',
        '// A type absent here carries no events.',
        'export const TYPE_EVENT_LISTS: Record<string, string[]> = {',
        ...lines,
        '};',
        '',
    ].join('\n');
}

/** mobile catalogExtensions.generated.ts: each extension type (since >= 3) and its mobile.reason. */
export function renderMobileExtensions(snapshot) {
    const lines = Object.entries(snapshot.types)
        .filter(([, entry]) => entry.since !== undefined)
        .map(([type, entry]) => `    ${IDENT.test(type) ? type : quote(type)}: ${quote(entry.mobile?.reason ?? '')},`);
    return [
        `// GENERATED by scripts/gen-app-catalog.mjs from ${SPEC_FILE}: do not edit. Run \`npm run gen:shared\`.`,
        '// The component types added after the base (since >= 3), each with the reason the phone',
        '// leaves it to the browser (its spec\'s mobile.reason). catalog.ts reads it.',
        `export const EXTENSION_TYPE_MOBILE_REASONS: Readonly<Record<string, string>> = {${lines.length ? '' : '};'}`,
        ...(lines.length ? [...lines, '};'] : []),
        '',
    ].join('\n');
}

/** The demo's GET /api/studio-apps/catalog answer: buildCatalog() with fewer components. */
export function buildDemoCatalog(specs, types = DEMO_TYPES) {
    const catalog = specs.buildCatalog();
    const components = {};
    for (const t of types) {
        if (!catalog.components[t]) throw new Error(`DEMO_TYPES names ${t}, which the catalog does not have`);
        components[t] = catalog.components[t];
    }
    return { ...catalog, components };
}

const json = (value) => `${JSON.stringify(value, null, 4)}\n`;

/** @returns {Array<{ file: string, text: string }>} every spec-derived output, repo-relative */
export function specOutputs(specs) {
    const snapshot = buildSnapshot(specs);
    return [
        { file: OUT.snapshot, text: json(snapshot) },
        { file: OUT.typeEvents, text: renderTypeEventLists(snapshot) },
        { file: OUT.demo, text: json(buildDemoCatalog(specs)) },
        { file: OUT.mobileExtensions, text: renderMobileExtensions(snapshot) },
    ];
}

/** The names of the AI builder's tools, in the order the server ships them. */
export function toolNamesOf(toolSchemas) {
    return toolSchemas.map((s) => s.function.name);
}

export function toolsOutput(toolSchemas) {
    return { file: OUT.tools, text: json(toolNamesOf(toolSchemas)) };
}

function load(root, file) {
    return createRequire(path.join(root, 'package.json'))(path.join(root, file));
}

/** Write (or with check, compare) the outputs under `root`. Returns the exit code. */
export function run({ root = ROOT, check = false, tools = false, log = console.log, error = console.error } = {}) {
    const outputs = tools ? [toolsOutput(load(root, TOOLS_FILE).TOOL_SCHEMAS)] : specOutputs(load(root, SPEC_FILE));
    const stale = [];
    for (const { file, text } of outputs) {
        const target = path.join(root, file);
        const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
        if (current === text) continue;
        stale.push(file);
        if (!check) {
            fs.mkdirSync(path.dirname(target), { recursive: true });
            fs.writeFileSync(target, text);
            log(`gen-app-catalog: wrote ${file}`);
        }
    }
    if (check && stale.length) {
        for (const file of stale) error(`gen-app-catalog: ${file} is out of date with ${SPEC_FILE}`);
        error('It is generated: do not edit it by hand. Run `npm run gen:shared` and commit the result.');
        return 1;
    }
    if (!stale.length) log(`gen-app-catalog: ${outputs.length} file${outputs.length === 1 ? '' : 's'} up to date.`);
    return 0;
}

if (isEntryPoint(import.meta.url)) {
    const argv = process.argv.slice(2);
    try {
        process.exitCode = run({ check: argv.includes('--check'), tools: argv.includes('--tools') });
    } catch (e) {
        console.error(`gen-app-catalog: ${e.message}`);
        process.exitCode = 1;
    }
}
