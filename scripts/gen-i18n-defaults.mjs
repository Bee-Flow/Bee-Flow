#!/usr/bin/env node
/**
 * gen-i18n-defaults — write the frontend's English dictionary from the
 * server's.
 *
 *   node scripts/gen-i18n-defaults.mjs           # (re)write the file
 *   node scripts/gen-i18n-defaults.mjs --check   # exit 1 if it is out of date
 *
 * Source: server/i18n/defaults/en/ (one file per namespace, merged by
 *         en/index.js into GUI_DEFAULTS) — the canonical catalogue, the one
 *         the server serves through the API.
 * Output: agent-hub/src/i18n/en-defaults.js — the client-side fallback so t()
 *         returns English when the API is unreachable. One `"key": "value",`
 *         line per key, in GUI_DEFAULTS order, JSON-quoted.
 *
 * The two used to be "kept manually in sync" and had drifted by five values;
 * concurrent branches appending to both tails lost each other's keys in
 * merges. Now there is one source and this copy. CI runs --check.
 *
 * Zero dependencies: node:* only, and the server dictionary is plain CommonJS
 * loaded through createRequire.
 */

import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

import { isEntryPoint } from './entry-point.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = path.join(ROOT, 'server', 'i18n', 'defaults', 'en', 'index.js');
const TARGET = path.join(ROOT, 'agent-hub', 'src', 'i18n', 'en-defaults.js');
const REL_TARGET = 'agent-hub/src/i18n/en-defaults.js';

const HEADER = `/**
 * English GUI defaults — GENERATED by scripts/gen-i18n-defaults.mjs from
 * server/i18n/defaults/en/ (one file per namespace). DO NOT EDIT BY HAND: change
 * the server file for the key's namespace, then run
 * \`node scripts/gen-i18n-defaults.mjs\`. CI fails when this file is out of date.
 * Client-side fallback so t() always returns English when the API is unavailable.
 *
 * Loaded NATIVELY in tests: vite.config.js lists this path in
 * test.server.deps.external so vite-node does not move 2 MB into every worker
 * thread. Keep the file transform-free — no imports, no JSX, no import.meta,
 * no '@' alias, no __APP_* define, just \`export default\` over a literal.
 * src/i18n/enDefaultsExternal.test.js fails if that changes.
 */
`;

export function render(dict) {
    const lines = Object.entries(dict).map(([k, v]) => {
        if (typeof v !== 'string') throw new Error(`key ${k}: value is not a string`);
        return `    ${JSON.stringify(k)}: ${JSON.stringify(v)},`;
    });
    return `${HEADER}\nconst EN_DEFAULTS = {\n${lines.join('\n')}\n};\n\nexport default EN_DEFAULTS;\n`;
}

function main() {
    const check = process.argv.includes('--check');
    const { GUI_DEFAULTS } = createRequire(import.meta.url)(SOURCE);
    const want = render(GUI_DEFAULTS);
    const have = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : null;
    const count = Object.keys(GUI_DEFAULTS).length;
    if (check) {
        if (have === want) {
            console.log(`gen-i18n-defaults: ${REL_TARGET} is up to date (${count} keys).`);
            return 0;
        }
        console.error(`gen-i18n-defaults: ${REL_TARGET} is out of date with server/i18n/defaults/en/.`);
        if (have !== null) {
            const a = have.split('\n');
            const b = want.split('\n');
            let i = 0;
            while (i < a.length && i < b.length && a[i] === b[i]) i++;
            console.error(`  first difference at line ${i + 1}:\n    committed: ${a[i] ?? '(end of file)'}\n    generated: ${b[i] ?? '(end of file)'}`);
        }
        console.error('It is generated — do not edit it by hand. Change server/i18n/defaults/en/<namespace>.js,\n'
            + 'then run `node scripts/gen-i18n-defaults.mjs` (or `npm run i18n:gen`) and commit the result.');
        return 1;
    }
    if (have === want) {
        console.log(`gen-i18n-defaults: ${REL_TARGET} already up to date (${count} keys).`);
    } else {
        fs.writeFileSync(TARGET, want);
        console.log(`gen-i18n-defaults: wrote ${REL_TARGET} (${count} keys).`);
    }
    return 0;
}

// Run as a command, not imported by a test (see entry-point.mjs).
if (isEntryPoint(import.meta.url)) {
    try {
        process.exitCode = main();
    } catch (e) {
        console.error(`gen-i18n-defaults: ${e.message}`);
        process.exitCode = 1;
    }
}
