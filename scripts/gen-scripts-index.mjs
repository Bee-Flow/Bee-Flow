#!/usr/bin/env node
/**
 * Write the index of scripts/ at the end of scripts/README.md, or check that it is current.
 *
 * One row per runnable file in scripts/ (`.mjs`, `.cjs`, `.js`, `.sh`, `.ps1`; tests and
 * sub-folders left out) with the first sentence of its header comment. The hand-written
 * sections of the README explain the scripts that need explaining; this table is what makes
 * every check, generator and codemod findable at all.
 *
 * A script without a header comment fails in both modes: the row is its header, so a new
 * script needs nothing here but a first sentence that says what it does.
 *
 *   node scripts/gen-scripts-index.mjs            write the table when it differs
 *   node scripts/gen-scripts-index.mjs --check    exit 1 when it is stale; writes nothing
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { isEntryPoint } from './entry-point.mjs';

const SCRIPTS_DIR = path.dirname(fileURLToPath(import.meta.url));
const RUNNABLE = /\.(?:mjs|cjs|js|sh|ps1)$/;
const TEST = /\.test\.[cm]?js$/;
const START = '<!-- scripts-index:start (generated by scripts/gen-scripts-index.mjs from the header comments; do not edit) -->';
const END = '<!-- scripts-index:end -->';
const MAX_LENGTH = 220;
const SECTION = [
    '## Every script',
    '',
    'Generated: one row per runnable file in this folder (tests left out) with the first sentence',
    'of its header comment. `npm run gen:scripts-index` rewrites the table; `npm run',
    'lint:scripts-index` (part of `check:fast`) fails when it is stale or when a script has no header',
    'comment. A new script needs nothing here but a header whose first sentence says what it does.',
    '',
].join('\n');

/** Lines that may stand between the top of a file and its header comment. */
const PREAMBLE = /^(?:#!.*|\/\/\s*@typecheck\b.*|['"]use strict['"];?|set -[a-z]+.*|)$/;

/**
 * The text of a file's header comment, markers stripped: the first block comment or run of
 * line comments after the shebang, an `// @typecheck` line and blank lines. '' when the file
 * starts with code.
 * @param {string} source
 * @param {string} name  the file name; its extension says which comment syntax applies
 */
export function headerText(source, name) {
    const lines = source.split(/\r?\n/);
    const hash = /\.(?:sh|ps1)$/.test(name);
    let i = 0;
    // A lone `#` between the shebang and the text is an empty comment line, not the header.
    while (i < lines.length && (PREAMBLE.test(lines[i].trim()) || (hash && lines[i].trim() === '#'))) i++;
    const first = (lines[i] || '').trim();
    const out = [];
    const block = hash ? ['<#', '#>'] : ['/*', '*/'];
    if (first.startsWith(block[0])) {
        for (; i < lines.length; i++) {
            const closed = lines[i].includes(block[1]);
            out.push(lines[i].replace(block[0], '').replace(/\*\/|#>/, '').replace(/^\s*\*+ ?/, ''));
            if (closed) break;
        }
    } else {
        const mark = hash ? /^\s*#(?!!) ?/ : /^\s*\/\/ ?/;
        for (; i < lines.length && mark.test(lines[i]); i++) out.push(lines[i].replace(mark, ''));
    }
    return out.join('\n').trim();
}

/**
 * The length of the separator that follows a script's name in its own header
 * ("` — ", " - ", ": "), or 0 when the header does not go on that way. Plain
 * string steps: the paragraph has its white space folded to single spaces.
 * @param {string} rest
 */
function separatorLength(rest) {
    let i = rest.startsWith('`') ? 1 : 0;
    while (rest[i] === ' ') i++;
    if (i >= rest.length || !'—–-:'.includes(rest[i])) return 0;
    const afterMark = i + 1;
    i = afterMark;
    while (rest[i] === ' ') i++;
    return i > afterMark ? i : 0;
}

/**
 * The first sentence of a header: its first paragraph on one line, cut after the first full
 * stop that ends a sentence (not the one in `e.g.`, in `...` or in a file name), without the
 * script's own name in front, and shortened at a word when it runs long.
 * @param {string} text
 * @param {string} name
 */
export function firstSentence(text, name) {
    const paragraph = text.split(/\n\s*\n/)[0].replace(/\s+/g, ' ').trim();
    // "name.sh — what it does": the row already names the script.
    const afterName = paragraph.startsWith(name) || paragraph.startsWith(`\`${name}\``)
        ? paragraph.slice(paragraph.indexOf(name) + name.length)
        : '';
    const skip = separatorLength(afterName);
    const own = skip ? afterName.slice(skip) : paragraph;
    const end = /(?<!\b(?:e\.g|i\.e|etc|vs)|\.)[.!?](?=\s+[A-Z`'"(]|$)/.exec(own);
    // A paragraph that introduces a list ends in a colon; the row is a statement.
    const sentence = (end ? own.slice(0, end.index + 1) : own).replace(/:$/, '');
    if (sentence.length <= MAX_LENGTH) return sentence;
    return `${sentence.slice(0, sentence.lastIndexOf(' ', MAX_LENGTH))} …`;
}

/**
 * One row per runnable script of `dir`, sorted by name: { name, purpose }.
 * @param {string} dir
 */
export function indexRows(dir) {
    return fs.readdirSync(dir, { withFileTypes: true })
        .filter((e) => e.isFile() && RUNNABLE.test(e.name) && !TEST.test(e.name))
        .map((e) => e.name)
        .sort()
        .map((name) => ({ name, purpose: firstSentence(headerText(fs.readFileSync(path.join(dir, name), 'utf8'), name), name) }));
}

/**
 * A sentence as the text of a table cell: a `|` would end the cell (also inside a code span),
 * and a `<kind>` outside a code span would be read as an HTML tag and vanish.
 * @param {string} text
 */
function cell(text) {
    return text.replaceAll('|', '\\|').split('`').map((part, i) => (i % 2 ? part : part.replaceAll('<', '\\<'))).join('`');
}

/** @param {{ name: string, purpose: string }[]} rows */
export function renderIndex(rows) {
    const body = rows.map((r) => `| \`${r.name}\` | ${cell(r.purpose)} |`);
    return [START, '| Script | What it does |', '|--------|--------------|', ...body, END].join('\n');
}

/**
 * The README with its generated block replaced, or with the section appended when it has none.
 * @param {string} readme
 * @param {string} block
 */
export function withIndex(readme, block) {
    const from = readme.indexOf(START);
    const to = readme.indexOf(END);
    if (from === -1 || to < from) return `${readme.trimEnd()}\n\n${SECTION}\n${block}\n`;
    return readme.slice(0, from) + block + readme.slice(to + END.length);
}

/**
 * @param {{ check?: boolean, dir?: string, log?: (line: string) => void, error?: (line: string) => void }} [opts]
 * @returns {number} the exit code
 */
export function run({ check = false, dir = SCRIPTS_DIR, log = console.log, error = console.error } = {}) {
    const rows = indexRows(dir);
    const silent = rows.filter((r) => !r.purpose).map((r) => r.name);
    if (silent.length) {
        error(`gen-scripts-index: no header comment in scripts/${silent.join(', scripts/')}. Start the file with a comment whose first sentence says what the script does.`);
        return 1;
    }
    const file = path.join(dir, 'README.md');
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
    const wanted = withIndex(current, renderIndex(rows));
    if (current === wanted) {
        log(`gen-scripts-index: ${rows.length} scripts, index up to date.`);
        return 0;
    }
    if (check) {
        const stale = rows.filter((r) => !current.includes(renderIndex([r]).split('\n')[3])).map((r) => r.name);
        error(`gen-scripts-index: the index in scripts/README.md is out of date${stale.length ? ` (${stale.join(', ')})` : ' (a row for a script that is gone)'}. Run \`npm run gen:scripts-index\` and commit the result.`);
        return 1;
    }
    fs.writeFileSync(file, wanted);
    log(`gen-scripts-index: wrote ${rows.length} rows to scripts/README.md`);
    return 0;
}

if (isEntryPoint(import.meta.url)) process.exit(run({ check: process.argv.includes('--check') }));
