/**
 * The two generated editor bundles in server/core/markdown/ and the hash that
 * says whether they are still the build of their sources.
 *
 *   editorSerialization.cjs   built from agent-hub/src/editor/serialization/index.js
 *   editorCollab.cjs          built from agent-hub/src/editor/collab/serverEntry.ts
 *
 * Both are esbuild bundles of agent-hub source the server cannot import
 * directly (the agent-hub image cannot see server/, and the server ships CJS).
 * A bundle nobody rebuilt after an editor change is a server that serialises
 * with yesterday's editor, with every test green. So the build puts a line in
 * the bundle's banner,
 *
 *     inputs-sha256: <hex>
 *
 * a sha256 over the content of every file esbuild bundled (its metafile
 * `inputs`), and scripts/check-editor-bundles.mjs recomputes it.
 *
 * The check must not need an install, so it cannot ask esbuild which files
 * went in. The banner therefore also lists them (`inputs:` line, relative to
 * server/). esbuild's own `// <path>` comments above each module would not do:
 * a module whose code is tree-shaken away gets none, yet it is an input.
 *
 * Zero dependencies: node:* only.
 */

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

export const HASH_LABEL = 'inputs-sha256:';
export const INPUTS_LABEL = 'inputs:';

const sortedInputs = (inputs) => [...new Set(inputs)].sort();

const COLLAB_EXTERNALS = ['yjs', 'y-protocols', 'lib0'];

/**
 * Paths are relative to server/, the working directory of the npm scripts and
 * the base of every path esbuild prints in the bundle.
 */
export const BUNDLES = {
    md: {
        script: 'build:editor-md',
        entry: '../agent-hub/src/editor/serialization/index.js',
        out: 'core/markdown/editorSerialization.cjs',
        options: {},
        banner: [],
        footer: '',
    },
    collab: {
        script: 'build:editor-collab',
        entry: '../agent-hub/src/editor/collab/serverEntry.ts',
        out: 'core/markdown/editorCollab.cjs',
        options: { target: 'node22', external: COLLAB_EXTERNALS },
        // Kept exactly as the npm script had it: eslint and jscpd skip the file.
        banner: ['/* eslint-disable */ /* jscpd:ignore-start */'],
        footer: '/* jscpd:ignore-end */',
    },
};

/** The banner text (without esbuild's trailing newline) for a bundle, its input hash and input paths. */
export function bannerFor(name, hash, inputs) {
    const b = BUNDLES[name];
    const generated = `/* GENERATED by 'cd server && npm run ${b.script}' from ${b.entry.replace(/^\.\.\//, '')}. Do not edit. */`;
    const first = b.banner.length ? `${generated} ${b.banner.join(' ')}` : generated;
    return `${first}\n/* ${HASH_LABEL} ${hash} */\n/* ${INPUTS_LABEL} ${sortedInputs(inputs).join(' ')} */`;
}

const norm = (text) => text.replace(/\r\n/g, '\n');

/**
 * sha256 over the sorted input paths and their content (CRLF read as LF, so a
 * Windows checkout hashes like a Linux one).
 * @param {string} baseDir directory the paths are relative to (server/)
 * @param {string[]} inputs
 * @returns {string} hex digest; throws when an input cannot be read
 */
export function hashInputs(baseDir, inputs) {
    const h = crypto.createHash('sha256');
    for (const rel of sortedInputs(inputs)) {
        const text = fs.readFileSync(path.resolve(baseDir, rel), 'utf8');
        h.update(`${rel}\n${norm(text)}\n\0`);
    }
    return h.digest('hex');
}

/** The recorded hash of a bundle's text, or null when its banner has none. */
export function recordedHash(bundleText) {
    const m = new RegExp(`^/\\* ${HASH_LABEL} ([0-9a-f]{64}) \\*/$`, 'm').exec(bundleText.slice(0, 2000));
    return m ? m[1] : null;
}

/** The input paths a bundle's banner lists; empty when it has none. */
export function recordedInputs(bundleText) {
    const m = new RegExp(`^/\\* ${INPUTS_LABEL} (.+) \\*/$`, 'm').exec(bundleText.slice(0, 20000));
    return m ? m[1].split(' ') : [];
}

/**
 * @returns {{ ok: boolean, message: string }}
 */
export function checkBundle(name, baseDir) {
    const b = BUNDLES[name];
    const file = path.join(baseDir, b.out);
    const fix = `run: cd server && npm run ${b.script}`;
    let text;
    try {
        text = fs.readFileSync(file, 'utf8');
    } catch {
        return { ok: false, message: `${b.out}: missing; ${fix}` };
    }
    const want = recordedHash(text);
    if (!want) return { ok: false, message: `${b.out}: no "${HASH_LABEL}" line in its banner (built by hand?); ${fix}` };
    const inputs = recordedInputs(text);
    if (!inputs.includes(b.entry)) {
        return { ok: false, message: `${b.out}: its banner does not list its entry ${b.entry}; ${fix}` };
    }
    let got;
    try {
        got = hashInputs(baseDir, inputs);
    } catch (e) {
        return { ok: false, message: `${b.out}: cannot read an input (${e.message}); ${fix}` };
    }
    if (got !== want) {
        return {
            ok: false,
            message: `${b.out}: stale, its sources changed after the last build (recorded ${want.slice(0, 12)}, now ${got.slice(0, 12)}); ${fix}`,
        };
    }
    return { ok: true, message: `${b.out}: up to date (${inputs.length} inputs, ${want.slice(0, 12)})` };
}
