/**
 * The shell functions behind several stacks on one machine, run on their own.
 *
 *   selfhost-sidecars.sh  networks_yaml: one internal network per stack, every
 *                         sidecar on all of them; valid_stack_name.
 *   selfhost.sh           wire_shared_sidecars: refuses a profile that is both
 *                         shared and run locally, requires the sidecars' key,
 *                         wires the service URLs and keeps an operator's own;
 *                         wire_bind_host: loopback for a named stack only.
 *
 * The functions are lifted out of the scripts by name (same technique as
 * selfhost-env-file.test.mjs) and run under bash with the helpers they call
 * stubbed: `docker` answers that the network exists unless told otherwise.
 *
 * Run: node --test scripts/selfhost-shared-sidecars.test.mjs
 */

import test from 'node:test';
import assert from 'node:assert';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { REPO, hasBash } from './lib/docker-stub.mjs';

const skip = hasBash ? false : 'needs bash';
const selfhost = fs.readFileSync(path.join(REPO, 'selfhost.sh'), 'utf8');
const sidecars = fs.readFileSync(path.join(REPO, 'selfhost-sidecars.sh'), 'utf8');

/** `name() {` … `\n}\n` of a top-level bash function. */
function lift(script, name) {
    const fn = new RegExp(`^${name}\\(\\) \\{[^\\n]*\\n[\\s\\S]*?\\n\\}\\n`, 'm').exec(script)?.[0];
    assert.ok(fn, `${name}() { ... } not found`);
    return fn;
}

function bash(t, lines, env = {}) {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'selfhost-shared-'));
    t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
    const envFile = path.join(dir, 'env');
    fs.writeFileSync(envFile, env.ENV_CONTENT ?? '');
    const script = [
        '#!/bin/bash',
        'set -eo pipefail',
        `ENV_FILE="${envFile}"`,
        'log() { echo "LOG $*"; }; ok() { :; }; warn() { :; }; err() { echo "ERR $*" >&2; exit 1; }',
        'docker() { [ "${NETWORK_MISSING:-}" = 1 ] && return 1; return 0; }',
        ...lines,
    ].join('\n');
    const res = spawnSync('bash', ['-c', script], { encoding: 'utf8', env: { ...process.env, ...env } });
    return { status: res.status, out: res.stdout, err: res.stderr };
}

test('networks_yaml: one internal network per stack, every sidecar on all of them', { skip }, (t) => {
    const r = bash(t, [lift(sidecars, 'networks_yaml'), 'networks_yaml "public internal"']);
    assert.strictEqual(r.status, 0, r.err);
    assert.strictEqual(r.out, [
        '# GENERATED by selfhost-sidecars.sh from SIDECAR_STACKS — do not edit, re-run the script.',
        'services:',
        '  guard-service:', '    networks:', '      - stack-public', '      - stack-internal',
        '  classify-service:', '    networks:', '      - stack-public', '      - stack-internal',
        '  ollama:', '    networks:', '      - stack-public', '      - stack-internal',
        'networks:',
        '  stack-public:', '    name: public-sidecars', '    internal: true',
        '  stack-internal:', '    name: internal-sidecars', '    internal: true',
        '',
    ].join('\n'));
});

test('valid_stack_name accepts compose project names only', { skip }, (t) => {
    const check = (name) => bash(t, [lift(sidecars, 'valid_stack_name'), `valid_stack_name '${name}'`]).status;
    assert.strictEqual(check('public'), 0);
    assert.strictEqual(check('team-b2'), 0);
    assert.notStrictEqual(check('Public'), 0, 'uppercase');
    assert.notStrictEqual(check('-x'), 0, 'leading dash');
    assert.notStrictEqual(check('a b'), 0, 'space');
    assert.notStrictEqual(check(''), 0, 'empty');
});

const WIRE = [lift(selfhost, 'default_env'), lift(selfhost, 'env_has'), lift(selfhost, 'wire_shared_sidecars')];
const wire = (t, shared, profiles, extra = [], env = {}) => bash(t, [
    `SHARED_SIDECARS="${shared}"`, `PROFILES="${profiles}"`, 'STACK_LABEL=internal', ...WIRE, ...extra,
    'wire_shared_sidecars',
    'echo "PII=${PII_SERVICE_URL:-} CLS=${CLASSIFY_SERVICE_URL:-} OLL=${OLLAMA_URL:-}"',
], env);

test('wire_shared_sidecars: a profile that is shared and run locally is refused', { skip }, (t) => {
    const r = wire(t, 'guard', 'core guard');
    assert.notStrictEqual(r.status, 0);
    assert.match(r.err, /shared guard or its own/);
});

test('wire_shared_sidecars: an unknown sidecar is refused', { skip }, (t) => {
    const r = wire(t, 'postgres', 'core');
    assert.notStrictEqual(r.status, 0);
    assert.match(r.err, /unknown sidecar "postgres"/);
});

test('wire_shared_sidecars: the per-stack network must exist', { skip }, (t) => {
    const r = wire(t, 'guard', 'core', [], { NETWORK_MISSING: '1', ENV_CONTENT: 'PII_SERVICE_API_KEY=k\n' });
    assert.notStrictEqual(r.status, 0);
    assert.match(r.err, /internal-sidecars does not exist/);
    assert.match(r.err, /selfhost-sidecars\.sh/);
});

test('wire_shared_sidecars: the sidecars\' key is required per shared service', { skip }, (t) => {
    const r = wire(t, 'guard classify', 'core', [], { ENV_CONTENT: 'PII_SERVICE_API_KEY=k\n' });
    assert.notStrictEqual(r.status, 0);
    assert.match(r.err, /CLASSIFY_SERVICE_API_KEY is empty/);
});

test('wire_shared_sidecars: wires the service names over the shared network', { skip }, (t) => {
    const r = wire(t, 'guard classify local-llm', 'core', [], { ENV_CONTENT: 'PII_SERVICE_API_KEY=k\nCLASSIFY_SERVICE_API_KEY=k\n' });
    assert.strictEqual(r.status, 0, r.err);
    assert.match(r.out, /PII=http:\/\/guard-service:8100 CLS=http:\/\/classify-service:8300 OLL=http:\/\/ollama:11434/);
});

test('wire_shared_sidecars: a URL the operator set in the env file or the environment is kept', { skip }, (t) => {
    const fromFile = wire(t, 'guard', 'core', [], { ENV_CONTENT: 'PII_SERVICE_API_KEY=k\nPII_SERVICE_URL=http://own-guard:1\n' });
    assert.strictEqual(fromFile.status, 0, fromFile.err);
    assert.match(fromFile.out, /PII= /, 'not exported over a value the env file carries (compose reads the file)');
    const fromEnv = wire(t, 'guard', 'core', [], { ENV_CONTENT: 'PII_SERVICE_API_KEY=k\n', PII_SERVICE_URL: 'http://env-guard:1' });
    assert.match(fromEnv.out, /PII=http:\/\/env-guard:1/);
});

test('wire_bind_host: loopback for a named stack, untouched for the plain install and over an explicit value', { skip }, (t) => {
    const run = (stack, env = {}) => bash(t, [
        lift(selfhost, 'default_env'), `STACK_NAME="${stack}"`, lift(selfhost, 'wire_bind_host'),
        'wire_bind_host', 'echo "BIND=${CLIENT_BIND_HOST:-}"',
    ], env);
    assert.match(run('internal').out, /BIND=127\.0\.0\.1/);
    assert.match(run('').out, /BIND=$/m);
    assert.match(run('internal', { CLIENT_BIND_HOST: '0.0.0.0' }).out, /BIND=0\.0\.0\.0/);
    assert.match(run('internal', { ENV_CONTENT: 'CLIENT_BIND_HOST=10.0.0.5\n' }).out, /BIND=$/m, 'the env file value reaches compose on its own');
});

test('the shared sidecars publish no port, and only Ollama has a way out', () => {
    const compose = fs.readFileSync(path.join(REPO, 'docker-compose.sidecars.yml'), 'utf8').split('\n');
    assert.ok(!compose.some((l) => l.trim().startsWith('ports:')), 'no published port');
    // Which services name which network, by indentation (services at 2, their keys at 4, list items at 6).
    const members = {};
    let service = null;
    let inServices = false;
    let inNetworks = false;
    for (const line of compose) {
        if (line.startsWith('services:')) { inServices = true; continue; }
        if (/^\S/.test(line)) inServices = false;
        if (!inServices) continue;
        if (line.startsWith('  ') && !line.startsWith('   ') && line.trim().endsWith(':')) { service = line.trim().slice(0, -1); inNetworks = false; continue; }
        if (line.startsWith('    ') && !line.startsWith('     ')) inNetworks = line.trim() === 'networks:';
        else if (inNetworks && line.trim().startsWith('- ')) (members[line.trim().slice(2)] ||= []).push(service);
    }
    assert.deepStrictEqual(members['sidecars-egress'], ['ollama']);
    assert.ok(!members['sidecars-internal'].includes('ollama'));
    const egressAt = compose.findIndex((l) => l.trim() === 'sidecars-egress:' && l.startsWith('  ') && !l.startsWith('   '));
    const internalAt = compose.findIndex((l) => l.trim() === 'sidecars-internal:' && l.startsWith('  ') && !l.startsWith('   '));
    assert.ok(compose.slice(internalAt, internalAt + 4).some((l) => l.trim() === 'internal: true'), 'the sidecars\' own network is internal');
    assert.ok(egressAt > internalAt, 'the egress network is declared');
});
